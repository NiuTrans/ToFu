/* ═══════════════════════════════════════════════════════════════════
   paper/deepen.js — On-demand section depth (design P3,
   docs/PAPER_READING_EXPERIENCE_DESIGN.md)

   "再深一层" on every report section heading, "逐步推导" on every display
   formula. Each click opens a drawer under the heading/formula and runs (or
   joins) a bounded agentic deepen task server-side; a fresh cache hit
   renders instantly and never re-bills. Depth cost is paid only when the
   reader actually asks.

   Contracts:
     • section indices enumerate the report's h2/h3 in document order,
       EXCLUDING the client-side xp sections — the same sequence the backend
       extracts from the stored report body (insight anchors share it);
     • events ride the generic task-routes poll ({ok, events, next_cursor,
       status}) + the 'paper' push channel (same dual transport as Q&A);
     • on done the drawer re-fetches the report meta (reportCache) so the
       finish tag's secondPasses.deepen total matches the server exactly.
   ═══════════════════════════════════════════════════════════════════ */

var _paperDeepenJobs = {};   // drawerKey → job

/** The report's own h2/h3 in document order (xp-internal headings excluded). */
function _deepenReportHeadings(article) {
  var all = article.querySelectorAll('h2, h3');
  var out = [];
  for (var i = 0; i < all.length; i++) {
    if (all[i].closest('.paper-xp-section, .paper-xp-card, .paper-xp-flip,'
        + ' .paper-deepen-drawer, .paper-xp-recap')) continue;
    out.push(all[i]);
  }
  return out;
}

function _deepenBtn(mode, secIdx, label) {
  // Icon-only markup: the visible label is generated by CSS ::after from
  // data-label, so the button contributes NOTHING to the heading's
  // textContent — TOC labels / reading anchors / h2.textContent stay clean.
  return '<button type="button" class="paper-deepen-btn xp-deep-' + mode +
    '" data-mode="' + mode + '" data-sec-idx="' + secIdx +
    '" data-label="' + escapeHtml(label) + '" aria-label="' + escapeHtml(label) +
    '" title="' + escapeHtml(label) + '">' +
    '<svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"><circle cx="11" cy="11" r="7"/><line x1="21" y1="21" x2="16.5" y2="16.5"/></svg>' +
    '</button>';
}

/** After-render seam (called by reading_xp._paperXpAfterRender): inject the
 *  deepen buttons. Idempotent — old buttons are removed first. */
function _paperDeepenAfterRender(article, container, view) {
  if (!article) return;
  var old = article.querySelectorAll('.paper-deepen-btn');
  for (var i = 0; i < old.length; i++) {
    if (old[i].parentNode) old[i].parentNode.removeChild(old[i]);
  }
  var _tt = (typeof t === 'function') ? t : function (k) { return k; };
  var heads = _deepenReportHeadings(article);
  for (var h = 0; h < heads.length; h++) {
    heads[h].insertAdjacentHTML('beforeend', _deepenBtn('deeper', h, _tt('paper.deepenBtn')));
    heads[h].setAttribute('data-deepen-sec', String(h));
  }
  // Derive buttons on display-math blocks (KaTeX).
  var maths = article.querySelectorAll('.katex-display');
  for (var m = 0; m < maths.length; m++) {
    // Containing section = last report heading before this math block.
    var sec = -1;
    for (var s = 0; s < heads.length; s++) {
      var rel = heads[s].compareDocumentPosition(maths[m]);
      if (rel & 4 /* DOCUMENT_POSITION_FOLLOWING */ || heads[s].contains(maths[m])) sec = s;
      else break;
    }
    if (sec < 0) continue;
    maths[m].insertAdjacentHTML('afterend',
      _deepenBtn('derive', sec, _tt('paper.deriveBtn')));
  }
}

function _deepenDrawerKey(mode, secIdx) { return mode + ':' + secIdx; }

/** Find or create the drawer for (mode, secIdx) under its heading. */
function _deepenDrawer(article, mode, secIdx) {
  var heads = _deepenReportHeadings(article);
  var h = heads[secIdx];
  if (!h) return null;
  var key = _deepenDrawerKey(mode, secIdx);
  var existing = article.querySelector('.paper-deepen-drawer[data-drawer="' + key + '"]');
  if (existing) return existing;
  var drawer = document.createElement('div');
  drawer.className = 'paper-deepen-drawer';
  drawer.setAttribute('data-drawer', key);
  h.insertAdjacentElement('afterend', drawer);
  return drawer;
}

function _deepenPaintRunning(drawer, secIdx, mode) {
  var _tt = (typeof t === 'function') ? t : function (k) { return k; };
  drawer.innerHTML =
    '<div class="paper-deepen-status"><span class="thinking-dot"></span> ' +
    escapeHtml(_tt('paper.deepenRunning')) + '</div>' +
    '<button type="button" class="paper-deepen-stop" data-stop="1">' +
    escapeHtml(_tt('paper.reportStop') || 'Stop') + '</button>';
}

function _deepenPaintContent(drawer, content, usage, cached) {
  var _tt = (typeof t === 'function') ? t : function (k) { return k; };
  var metaLine = '';
  if (usage && (usage.prompt_tokens || usage.completion_tokens)) {
    var fmt = function (n) {
      n = n | 0;
      if (n >= 1000) return (n / 1000).toFixed(1) + 'k';
      return String(n);
    };
    metaLine = '<div class="paper-deepen-meta">' +
      (cached ? escapeHtml(_tt('paper.deepenCached')) + ' · ' : '') +
      fmt(usage.prompt_tokens) + ' → ' + fmt(usage.completion_tokens) + ' tok</div>';
  }
  drawer.innerHTML = '<div class="paper-deepen-body">'
    + ((typeof renderMarkdown === 'function') ? renderMarkdown(content || '')
                                               : escapeHtml(content || ''))
    + '</div>' + metaLine;
}

function _deepenPaintError(drawer, msg) {
  drawer.innerHTML = '<div class="paper-deepen-status paper-deepen-error">' +
    escapeHtml(msg || 'deepen failed') + '</div>';
}

/** Sync the finish tag from the server's (post-accumulation) report meta. */
async function _deepenSyncReportMeta(view) {
  try {
    if (!view || typeof Api === 'undefined' || !Api.paper || !Api.paper.reportCache) return;
    var langKey = (typeof view.langKey === 'function') ? view.langKey() : null;
    if (!langKey || !_paperHash) return;
    var data = await Api.paper.reportCache({ lang: langKey, paper_hash: _paperHash });
    if (data && data.ok && data.meta) {
      var s = (view.stream) || { kind: view.kind || 'report' };
      window._paperXpApplyMetaEvent(s, { type: 'report_meta', meta: data.meta }, view);
    }
  } catch (e) {
    console.debug('[Paper:Deepen] meta sync failed (non-fatal):', e);
  }
}

async function _paperDeepenPoll(job, view) {
  var cursor = 0;
  var POLL_MS = 800;
  while (true) {
    if (job.stopped) return;
    var resp = await Api.paper.deepenPoll(job.taskId, cursor);
    if (!resp || !resp.ok) return;
    var data = await resp.json();
    if (!data || data.ok === false) {
      _deepenPaintError(job.drawer, (data && data.error) || 'poll failed');
      return;
    }
    var events = data.events || [];
    for (var i = 0; i < events.length; i++) {
      var ev = events[i];
      if (ev.type === 'delta') {
        job.content += (ev.delta || '');
        // Live-stream into the drawer (plain text until done — markdown
        // reparses on completion, matching the report's stream→final path).
        var body = job.drawer.querySelector('.paper-deepen-body');
        if (body) body.textContent = job.content;
      } else if (ev.type === 'delta_reset') {
        job.content = '';
      } else if (ev.type === 'done') {
        job.status = 'done';
        _deepenPaintContent(job.drawer, ev.content || job.content, ev.usage, false);
        _deepenSyncReportMeta(view);
        return;
      } else if (ev.type === 'error') {
        job.status = 'error';
        var emsg = (typeof errorEnvelopeMessage === 'function')
          ? errorEnvelopeMessage(ev.error) : (ev.error || 'deepen failed');
        _deepenPaintError(job.drawer, emsg);
        return;
      } else if (ev.type === 'aborted') {
        job.status = 'aborted';
        return;
      }
    }
    cursor = data.next_cursor;
    if (data.status === 'done' || data.status === 'error' || data.status === 'aborted') {
      // Terminal without a done event (edge) — paint whatever streamed.
      if (job.status !== 'done') _deepenPaintContent(job.drawer, job.content, null, false);
      return;
    }
    await new Promise(function (r) { setTimeout(r, POLL_MS); });
  }
}

async function _paperDeepenStart(btn) {
  var container = document.getElementById('paperReportContent');
  var article = container && container.querySelector('.paper-report-article');
  if (!article) return;
  var mode = btn.getAttribute('data-mode') || 'deeper';
  var secIdx = parseInt(btn.getAttribute('data-sec-idx') || '-1', 10);
  if (secIdx < 0) return;
  var key = _deepenDrawerKey(mode, secIdx);
  var existing = _paperDeepenJobs[key];
  if (existing && (existing.status === 'running' || existing.status === 'done')) {
    // Toggle the drawer closed on a second click instead of double-billing.
    if (existing.drawer) existing.drawer.remove();
    delete _paperDeepenJobs[key];
    return;
  }
  var drawer = _deepenDrawer(article, mode, secIdx);
  if (!drawer) return;
  var view = (typeof _reportView === 'function') ? _reportView('report') : null;
  var job = { taskId: null, status: 'running', content: '', drawer: drawer,
              mode: mode, secIdx: secIdx, stopped: false };
  _paperDeepenJobs[key] = job;
  _deepenPaintRunning(drawer, secIdx, mode);

  var langKey = (view && typeof view.langKey === 'function') ? view.langKey()
    : ((typeof _activeReportLang === 'function') ? _activeReportLang() : 'en');
  var model = (view && view.model) || undefined;
  try {
    var data = await Api.paper.deepenStart({
      paper_hash: _paperHash || '',
      section_idx: secIdx,
      mode: mode,
      lang: langKey,
      paper_text: (typeof _paperParsedText !== 'undefined') ? _paperParsedText : '',
      model: model,
    });
    if (!data || !data.ok) throw new Error((data && data.error) || 'deepen start failed');
    if (data.cached) {
      job.status = 'done';
      _deepenPaintContent(drawer, data.content, data.usage, true);
      return;
    }
    job.taskId = data.task_id;
    await _paperDeepenPoll(job, view);
  } catch (e) {
    console.warn('[Paper:Deepen] failed:', e);
    job.status = 'error';
    _deepenPaintError(drawer, e && e.message ? e.message : String(e));
  }
}

if (typeof window !== 'undefined') {
  window._paperDeepenAfterRender = _paperDeepenAfterRender;
  window._deepenReportHeadings = _deepenReportHeadings;
  if (!window._paperDeepenClickWired) {
    window._paperDeepenClickWired = true;
    document.addEventListener('click', function (ev) {
      var stop = ev.target && ev.target.closest
        ? ev.target.closest('.paper-deepen-stop') : null;
      if (stop) {
        var drawer = stop.closest('.paper-deepen-drawer');
        var key = drawer && drawer.getAttribute('data-drawer');
        var job = key && _paperDeepenJobs[key];
        if (job) {
          job.stopped = true;
          job.status = 'aborted';
          if (job.taskId && typeof Api !== 'undefined') {
            Api.paper.deepenAbort(job.taskId).catch(function () {});
          }
          if (drawer) drawer.remove();
          delete _paperDeepenJobs[key];
        }
        return;
      }
      var btn = ev.target && ev.target.closest
        ? ev.target.closest('.paper-deepen-btn') : null;
      if (btn) _paperDeepenStart(btn);
    });
  }
}
