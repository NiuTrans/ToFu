// Derive the closed validator contract and types from the root schema authority.
import fs from 'node:fs';
const schema = JSON.parse(fs.readFileSync(new URL('../../contracts/rich_response_v1.schema.json', import.meta.url), 'utf8'));
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(' | ');
  if (s.oneOf) return s.oneOf.map(type).join(' | ');
  if (s.type === 'array') return `Array<${type(s.items)}>`;
  if (s.type === 'object') return `{ ${Object.entries(s.properties).map(([k,v]) => `${k}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`).join('; ')} }`;
  return s.type;
}
const output = '// Generated by frontend/scripts/generate-rich-response.mjs. Do not edit.\n'
 + Object.entries(schema.$defs).map(([k,v]) => `export type ${k} = ${type(v)};`).join('\n')
 + `\nexport type RichResponse = ${type(schema)};\nexport const richResponseSchema = ${JSON.stringify(schema)} as const;\n`;
const target = new URL('../src/rich-response/contract.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Rich response contract is stale');
} else { fs.mkdirSync(new URL('../src/rich-response/', import.meta.url), {recursive:true}); fs.writeFileSync(target, output); }
