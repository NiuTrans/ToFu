"""Rootfs assembly (README §5): ubuntu-base, pinned packages, script effects.

Entry points: ``assemble_rootfs`` (fills a ``Tree``) and
``configure_ca_certificates`` (what ca-certificates' postinst and
``update-ca-certificates --hooksdir ""`` do on a fresh install, computed on
the build host). Dependencies: stdlib, the ``openssl`` executable (subject
hashes, the algorithm of ``openssl rehash``).
"""
from __future__ import annotations

import hashlib
from pathlib import PurePosixPath
import shutil
import ssl
import subprocess
import tarfile

from . import debs
from .tree import Tree, TreeError

ARCHITECTURE = 'arm64'
MOUNT_POINTS = ('opt/tofu', 'var/lib/tofu')
HOSTS = (b'127.0.0.1\tlocalhost\n'
         b'::1\tlocalhost ip6-localhost ip6-loopback\n'
         b'ff02::1\tip6-allnodes\n'
         b'ff02::2\tip6-allrouters\n')
CA_SOURCE_DIR = 'usr/share/ca-certificates'
CA_LOCAL_DIR = 'usr/local/share/ca-certificates'
CA_CONF = 'etc/ca-certificates.conf'
CA_CERTS_DIR = 'etc/ssl/certs'
CA_BUNDLE = 'ca-certificates.crt'
# Verbatim header the postinst writes before the certificate list.
CA_CONF_HEADER = """\
# This file lists certificates that you wish to use or to ignore to be
# installed in /etc/ssl/certs.
# update-ca-certificates(8) will update /etc/ssl/certs by reading this file.
#
# This is autogenerated by dpkg-reconfigure ca-certificates.
# Certificates should be installed under /usr/share/ca-certificates
# and files with extension '.crt' is recognized as available certs.
#
# line begins with # is comment.
# line begins with ! is certificate filename to be deselected.
#
"""
# Suffixes `openssl rehash` scans (apps/rehash.c).
REHASH_SUFFIXES = ('.pem', '.crt', '.cer', '.crl')

# Every maintainer script of the pinned packages, reviewed against what a
# fresh install (or the perl-base upgrade) would do. Only ca-certificates'
# configure step has an effect, and configure_ca_certificates reproduces it.
# Packages whose only script is `activate-noawait ldconfig` are omitted: the
# new libraries live in /usr/lib/aarch64-linux-gnu, which the arm64 loader
# searches by default, so a stale /etc/ld.so.cache only costs a lookup.
MAINTAINER_SCRIPT_REVIEW = {
    'ca-certificates': 'postinst configure: writes /etc/ca-certificates.conf (all certificates '
                       'trusted, the debconf default), creates /usr/local/share/ca-certificates and '
                       'runs update-ca-certificates; reproduced by the builder',
    'git': 'pre/postinst: dpkg-maintscript-helper rm_conffile for versions before 1:1.8.0 and a '
           '/var/lib/git migration for upgrades from before 1:1.8.4; no effect on a fresh install',
    'openssl': 'postinst: links /usr/lib/ssl to /etc/ssl only when /usr/lib/ssl is absent; the '
               'package ships /usr/lib/ssl, so no effect',
    'perl': 'postinst: removes a legacy "rename" alternative and fires perl-major-upgrade for '
            'upgrades from before 5.38; no effect',
    'perl-base': 'scripts: dpkg-maintscript-helper symlink_to_dir for versions before 5.30.0-1; '
                 'no effect on the 5.38.2 upgrade',
    'libgssapi-krb5-2': 'postinst: copies /usr/etc/gss/mech for upgrades from before 1.12.1; no '
                        'effect',
}


def assemble_rootfs(tree: Tree, base_tarball: str, packages: list[tuple[str, str]]) -> dict:
    """ubuntu-base plus pinned packages; returns the report fields."""
    with tarfile.open(base_tarball) as archive:
        tree.import_tar(archive)
    base_status = tree.get(debs.DPKG_STATUS)
    with open(base_status.source, encoding='utf-8') as handle:
        base_versions = debs.installed_from_status(handle.read()).versions
    installed = debs.unpack_packages(tree, packages, ARCHITECTURE)
    configure_ca_certificates(tree)
    tree.add_bytes('etc/hosts', HOSTS, tree.get('etc/hosts').mode, replace=True)
    for mount_point in MOUNT_POINTS:
        tree.ensure_dir(mount_point)
    return {
        'added': {package.name: package.version for package in installed
                  if package.name not in base_versions},
        'upgraded': {package.name: [base_versions[package.name], package.version]
                     for package in installed if package.name in base_versions},
        'maintainer_scripts': MAINTAINER_SCRIPT_REVIEW,
    }


def _content(tree: Tree, path: str) -> bytes:
    entry = tree.get(path)
    if entry is None or entry.type not in ('file', 'hardlink'):
        raise TreeError(f'{path} is not a regular file in the rootfs')
    with open(entry.source, 'rb') as handle:
        return handle.read()


def _pem_name(certificate: str) -> str:
    """update-ca-certificates' add(): spaces to '_', parentheses to '=', commas to '_'."""
    stem = PurePosixPath(certificate).name
    if stem.endswith('.crt'):
        stem = stem[:-4]
    return stem.replace(' ', '_').replace('(', '=').replace(')', '=').replace(',', '_') + '.pem'


def subject_hash(pem: bytes) -> str:
    openssl = shutil.which('openssl')
    if openssl is None:
        raise TreeError('the openssl executable is required for certificate subject hashes')
    result = subprocess.run([openssl, 'x509', '-noout', '-subject_hash'], input=pem,
                            capture_output=True, check=False)
    if result.returncode != 0:
        raise TreeError('openssl x509 -subject_hash failed: '
                        + result.stderr.decode('utf-8', 'replace').strip())
    return result.stdout.decode('ascii').strip()


def configure_ca_certificates(tree: Tree) -> None:
    """The fresh-install configure step of ca-certificates, without debconf.

    The debconf default trusts every available certificate, so the generated
    configuration lists all of them, sorted in the C locale as the postinst's
    ``sort`` does. ``update-ca-certificates`` then links each one into
    /etc/ssl/certs, concatenates the bundle in configuration order (adding a
    missing final newline) and lets ``openssl rehash`` add ``<hash>.<n>``
    links over the sorted file names.
    """
    if tree.get(CA_LOCAL_DIR) is None:
        tree.add_dir(CA_LOCAL_DIR, tree.get('usr/local').mode)
    prefix = CA_SOURCE_DIR + '/'
    certificates = sorted(
        (path[len(prefix):] for path, entry in tree.entries.items()
         if path.startswith(prefix) and path.endswith('.crt') and entry.type == 'file'),
        key=lambda name: name.encode('utf-8'))
    if not certificates:
        raise TreeError('ca-certificates shipped no certificates')
    configuration = CA_CONF_HEADER + ''.join(f'{name}\n' for name in certificates)
    tree.add_bytes(CA_CONF, configuration.encode('utf-8'), 0o644)

    bundle = bytearray()
    linked: dict[str, bytes] = {}
    for name in certificates:
        content = _content(tree, f'{CA_SOURCE_DIR}/{name}')
        pem = _pem_name(name)
        tree.add_symlink(f'{CA_CERTS_DIR}/{pem}', f'/{CA_SOURCE_DIR}/{name}')
        linked[pem] = content
        bundle += content if content.endswith(b'\n') or not content else content + b'\n'

    buckets: dict[str, list[str]] = {}
    for filename in sorted(linked, key=lambda name: name.encode('utf-8')):
        if not filename.endswith(REHASH_SUFFIXES):
            continue
        content = linked[filename]
        fingerprint = hashlib.sha1(ssl.PEM_cert_to_DER_cert(content.decode('ascii'))).hexdigest()
        bucket = buckets.setdefault(subject_hash(content), [])
        if fingerprint in (row.split('\0')[1] for row in bucket):
            continue
        bucket.append(f'{filename}\0{fingerprint}')
    for hash_value, rows in buckets.items():
        for index, row in enumerate(rows):
            tree.add_symlink(f'{CA_CERTS_DIR}/{hash_value}.{index}', row.split('\0')[0])
    tree.add_bytes(f'{CA_CERTS_DIR}/{CA_BUNDLE}', bytes(bundle), 0o644)
