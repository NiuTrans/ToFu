"""Generate the exact pinned grep-ast pack catalog without importing the package.

The upstream source hash is the admission boundary. Updating it requires reviewing
the upstream resolver and map plus rerunning the independent Python oracle.
"""
import argparse
import ast
import hashlib
import json
import posixpath
import random
from pathlib import Path

UPSTREAM_VERSION = '0.9.0'
UPSTREAM_SHA256 = '480c298ff045a0ef8de492eba55de2f230e21945fa671b3ed315bfc691c357b0'
ROOT = Path(__file__).resolve().parent


def generate(upstream, python_output=None):
    source = upstream.read_bytes()
    if hashlib.sha256(source).hexdigest() != UPSTREAM_SHA256:
        raise ValueError('unreviewed upstream catalog source; review before changing the pin')
    module = ast.parse(source)
    branch = next(node for node in module.body if isinstance(node, ast.If))
    assert isinstance(branch.test, ast.Name) and branch.test.id == 'USING_TSL_PACK'
    assignment = branch.body[0]
    assert assignment.targets[0].id == 'PARSERS'
    catalog = ast.literal_eval(assignment.value)
    assert all(isinstance(k, str) and isinstance(v, str) for k, v in catalog.items())
    lines = ['// Generated by generate_catalog.py; do not edit.',
             '// Mapping from grep-ast 0.9.0 (Apache-2.0); see LICENSE.grep-ast.txt.',
             '// Upstream parsers.py SHA256: ' + UPSTREAM_SHA256,
             'pub const LANGUAGES: &[(&str, &str)] = &[']
    lines += ['    (' + json.dumps(k) + ', ' + json.dumps(v) + '),' for k, v in sorted(catalog.items())]
    lines.append('];')
    # Expected paths use CPython posixpath; they do not use the Rust resolver.
    names = ['', '.', '..', '/', '//', '/a/', '.js', '..js', '...js', 'a..js',
             '.a.js', 'a.b/.js', 'a.py/.hidden', 'Dockerfile.js', 'xDockerfile',
             'a\\Dockerfile', 'C:\\a\\sample.js', 'a\\.js', '界.js', 'a\n.js']
    for key in sorted(catalog):
        names += [key, 'dir/' + key, 'file' + key, 'dir/.hidden' + key,
                  'dir/' + key.upper(), 'a.b/' + key + '/']
    rng = random.Random(905031)
    for _ in range(1000):
        names.append(''.join(rng.choice('abc./\\界😀\n') for _ in range(rng.randrange(24)))
                     + rng.choice(['.js', '.rs', '', '.PY', '.XCompose']))
    expected = [[name, catalog.get(posixpath.basename(name), catalog.get(posixpath.splitext(name)[1]))]
                for name in names]
    license_path = upstream.parent.parent / ('grep_ast-' + UPSTREAM_VERSION + '.dist-info/licenses/LICENSE.txt')
    outputs = {
        ROOT / 'src/catalog_generated.rs': '\n'.join(lines) + '\n',
        ROOT / 'tests/fixtures/catalog_cases.json': '[\n' + ',\n'.join(
            '  ' + json.dumps(row, ensure_ascii=False) for row in expected) + '\n]\n',
        ROOT / 'LICENSE.grep-ast.txt': license_path.read_text(),
    }
    if python_output is not None:
        outputs[python_output.parent / 'LICENSE.grep-ast.txt'] = license_path.read_text()
        outputs[python_output] = (
            '# Generated by packages/tofu-repo-kernel/rust/extraction/generate_catalog.py; do not edit.\n'
            '# grep-ast 0.9.0, Apache-2.0; see adjacent LICENSE.grep-ast.txt.\n'
            '# Upstream parsers.py SHA256: ' + UPSTREAM_SHA256 + '\n'
            'CATALOG_EXTENSIONS = frozenset([\n' + ''.join(
                '    ' + repr(key) + ',\n' for key in sorted(catalog) if key.startswith('.')) + '])\n')
    return outputs



def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--python-output', type=Path, help='optional explicit Python admission projection')
    args = parser.parse_args()
    for path, text in generate(args.upstream, args.python_output).items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise ValueError('generated catalog drift: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == '__main__':
    main()
