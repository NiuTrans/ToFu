"""Generate the research progress TypeScript projection from its JSON schema."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/research_progress_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/research-progress.generated.ts'


def ts_type(schema):
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind = schema['type']
    if isinstance(kind, list):
        return ' | '.join(ts_type({'type': k}) for k in kind)
    if kind == 'object':
        return '{\n' + ''.join(f'  {k}: {ts_type(v)};\n' for k, v in schema['properties'].items()) + '}'
    return {'integer': 'number', 'string': 'string', 'boolean': 'boolean', 'null': 'null'}[kind]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    text = '// Generated by scripts/generate_research_progress.py; do not edit.\n'
    text += 'export type ResearchProgressV1 = ' + ts_type(schema) + ';\n'

    text += 'const schema = ' + json.dumps(schema, ensure_ascii=False) + ';\n'
    text += '''
function validates(value: unknown, rule: any): boolean {
  if (rule.const !== undefined) return value === rule.const;
  if (rule.enum) return rule.enum.includes(value);
  if (Array.isArray(rule.type)) return rule.type.some((type: string) => validates(value, {...rule, type}));
  if (rule.type === 'null') return value === null;
  if (rule.type === 'integer') return Number.isSafeInteger(value) && Number(value) >= (rule.minimum ?? -Infinity) && Number(value) <= (rule.maximum ?? Infinity);
  if (rule.type === 'string') return typeof value === 'string' && value.length <= (rule.maxLength ?? Infinity);
  if (rule.type === 'boolean') return typeof value === 'boolean';
  if (rule.type === 'object') {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
    const row = value as Record<string, unknown>;
    return (rule.required || []).every((key: string) => key in row)
      && Object.entries(row).every(([key, item]) => rule.properties[key]
        ? validates(item, rule.properties[key]) : rule.additionalProperties !== false);
  }
  return false;
}
export function isResearchProgressV1(value: unknown): value is ResearchProgressV1 {
  return validates(value, schema);
}
'''
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit('research progress generated contract drift')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
