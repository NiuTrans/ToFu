#!/usr/bin/env python3
"""Generate shared inspector projection constants; --check verifies both outputs."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contract = json.loads((ROOT / 'contracts/request_inspector_projection_v1.json').read_text())
    name, fields = contract['contract'], contract['snapshotFields']
    outputs = {
        ROOT / 'lib/task_replay/generated_request_inspector_projection.py': (
            '"""Generated by scripts/gen_request_inspector_projection.py; do not edit."""\n'
            f'PROJECTION = {name!r}\nSNAPSHOT_FIELDS = {tuple(fields)!r}\n'),
        ROOT / 'packages/tofu-db/src/generated_request_inspector_projection.rs': (
            '// Generated by scripts/gen_request_inspector_projection.py; do not edit.\n'
            f'pub(crate) const PROJECTION: &str = {json.dumps(name)};\n'
            'pub(crate) const SNAPSHOT_FIELDS: &[&str] = &[\n'
            + ''.join(f'    {json.dumps(field)},\n' for field in fields) + '];\n'),
    }
    drift = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if drift:
        parser.exit(1, 'Regenerate request inspector projection: ' + ', '.join(drift) + '\n')


if __name__ == '__main__':
    main()
