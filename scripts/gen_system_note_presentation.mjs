#!/usr/bin/env node

/**
 * Generate the frontend system-note reason presentation contract from the
 * backend injection registry — the single source of truth.
 *
 * `lib/tasks_pkg/context_composer/registry.py::InjectionSpec.presentation`
 * declares, per intervention reason, the i18n label key and the category
 * tone. This generator turns that into a typed TypeScript map so the
 * conversation renderers (typed surface + retained JS runtime) never
 * hand-duplicate the vocabulary. Run `npm run generate:note-presentation`.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(
  repositoryRoot, 'frontend/src/conversation/ui/system-note-presentation.generated.ts');

const REGISTRY_READER = String.raw`
import json
from lib.tasks_pkg.context_composer.registry import note_presentations, note_display_policies
print(json.dumps({
    'presentations': {
        reason: {'labelKey': p.label_key, 'tone': p.tone, 'fallback': p.fallback}
        for reason, p in note_presentations().items()
    },
    'policies': note_display_policies(),
}, sort_keys=True))
`;

function readRegistryPresentations() {
  const stdout = execFileSync(
    'python3', ['-B', '-c', REGISTRY_READER],
    { cwd: repositoryRoot, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 },
  );
  return JSON.parse(stdout);
}

function renderContract({ presentations, policies }) {
  const reasons = Object.keys(presentations).sort();
  const entries = reasons.map((reason) => {
    const p = presentations[reason];
    return `  ${JSON.stringify(reason)}: { labelKey: ${JSON.stringify(p.labelKey)},`
      + ` tone: ${JSON.stringify(p.tone)}, fallback: ${JSON.stringify(p.fallback)} },`;
  });
  return `/**
 * Generated by scripts/gen_system_note_presentation.mjs.
 * Source authority: lib/tasks_pkg/context_composer/registry.py
 *   (InjectionSpec.presentation — note_label_key + note_tone per reason).
 * Do not edit this file directly; regenerate with
 *   npm run generate:note-presentation
 */

export type SystemNoteReasonTone = 'ok' | 'warn' | 'err' | 'info';

export interface SystemNoteReasonPresentation {
  readonly labelKey: string;
  readonly tone: SystemNoteReasonTone;
  readonly fallback: string;
}

/* Reason-id -> title-chip presentation. The label key resolves through the
 * i18n contract; the tone selects the chip colour (.sw-note-reason-{tone}).
 * A reason absent here (a newer backend) renders the neutral info chip with
 * the raw id, preserving the closed-world fallback contract. */
export const SYSTEM_NOTE_REASON_PRESENTATION: Readonly<
  Record<string, SystemNoteReasonPresentation>
> = {
${entries.join('\n')}
} as const;

/** Source-lane taxonomy; consumers must not maintain reason whitelists. */
export interface SystemNoteDisplayPolicy {
  readonly noteKind: string;
  readonly groupContext: boolean;
  readonly provenanceField: string;
}
export const SYSTEM_NOTE_DISPLAY_POLICY: Readonly<Record<string, SystemNoteDisplayPolicy>> = ${JSON.stringify(policies, null, 2)};
`;
}

export async function generateSystemNotePresentation({ check = false } = {}) {
  const expected = renderContract(readRegistryPresentations());
  let actual = '';
  try {
    actual = await fs.readFile(outputPath, 'utf8');
  } catch (error) {
    if (!error || error.code !== 'ENOENT') throw error;
  }
  if (actual === expected) return { changed: false };
  if (check) {
    throw new Error(
      `${path.relative(repositoryRoot, outputPath)} is stale; `
      + 'run npm run generate:note-presentation',
    );
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, expected, 'utf8');
  return { changed: true };
}

async function main() {
  const mode = process.argv[2] || '--write';
  if (!['--write', '--check'].includes(mode)) {
    throw new Error('usage: gen_system_note_presentation.mjs [--write|--check]');
  }
  const result = await generateSystemNotePresentation({ check: mode === '--check' });
  process.stdout.write(
    `system-note presentation contract ${result.changed ? 'generated' : 'verified'}\n`,
  );
}

const invokedPath = process.argv[1]
  ? new URL(`file://${path.resolve(process.argv[1])}`).href
  : '';
if (invokedPath === import.meta.url) {
  await main();
}
