#!/usr/bin/env python3
"""Generate the frozen storage.v1 semantic-operation catalog for Tofu-DB.

The Python Sidecar remains the executable authority.  This generator records
the exact compatibility surface that a future Tofu-DB backend must satisfy;
it deliberately records no SQL or handler implementation details.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import sys

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from lib.storage_sidecar.operation_domains import REGISTRY_VERSION  # noqa: E402
from lib.storage_sidecar.operation_registry import _DOMAIN_MODULES  # noqa: E402
from lib.storage_sidecar.schema import SCHEMA_VERSION  # noqa: E402


JSON_OUTPUT = REPOSITORY_ROOT / "contracts" / "storage_operations_v1.json"
PYTHON_OUTPUT = REPOSITORY_ROOT / "scripts" / "generated_storage_operations.py"
RUST_OUTPUT = (
    REPOSITORY_ROOT
    / "packages"
    / "tofu-db"
    / "src"
    / "generated_storage_operations.rs"
)


def _document() -> dict:
    from importlib import import_module

    from lib.task_event_contract import (
        EVENT_READ_GUARD_CONTRACT, EVENT_READ_GUARD_SCOPED_CONTRACT,
        EVENT_READ_GUARD_MAX_TYPES,
    )

    operations: list[dict] = []
    for domain in _DOMAIN_MODULES:
        module = import_module(
            f"lib.storage_sidecar.operation_domains.{domain}"
        )
        for name, spec in module.OPERATIONS.items():
            operations.append({
                "name": name,
                "domain": domain,
                "kind": spec.kind,
                "receiptRequired": bool(spec.receipt_required),
                "transactionTimeoutSeconds": spec.transaction_timeout_s,
                # Existing handlers enforce owner scope.  Making that fact
                # explicit prevents a new backend from mistaking omission in
                # this legacy catalog for permission to run unscoped.
                "ownerScope": "handler-enforced",
            })
    operations.sort(key=lambda item: item["name"])
    canonical_operations = json.dumps(
        operations, ensure_ascii=False, separators=(",", ":"), sort_keys=True
    ).encode("utf-8")
    return {
        "format": "tofu.storage-operation-catalog.v1",
        "generatedBy": "scripts/gen_storage_operation_catalog.py",
        "sourceProtocol": "storage.v1",
        "sourceSchemaVersion": SCHEMA_VERSION,
        "sourceRegistryVersion": REGISTRY_VERSION,
        "operationCount": len(operations),
        "operationsSha256": hashlib.sha256(canonical_operations).hexdigest(),
        "operations": operations,
        "eventReadGuardContract": EVENT_READ_GUARD_CONTRACT,
        "eventReadGuardScopedContract": EVENT_READ_GUARD_SCOPED_CONTRACT,
        "eventReadGuardMaxTypes": EVENT_READ_GUARD_MAX_TYPES,
    }


def _rust_string(value: str) -> str:
    """Render the catalog's ASCII identifiers as Rust string literals."""

    if not value.isascii():
        raise ValueError(f"Rust catalog identifier is not ASCII: {value!r}")
    return json.dumps(value)


def _render_rust(document: dict) -> str:
    kind_names = {
        "query": "Query",
        "command": "Command",
        "maintenance": "Maintenance",
    }
    lines = [
        "//! @generated by scripts/gen_storage_operation_catalog.py; do not edit.",
        "",
        f"pub const STORAGE_SCHEMA_VERSION: u32 = {document['sourceSchemaVersion']};",
        f"pub const STORAGE_REGISTRY_VERSION: u32 = {document['sourceRegistryVersion']};",
        f"pub const STORAGE_OPERATION_COUNT: usize = {document['operationCount']};",
        "pub const STORAGE_OPERATIONS_SHA256: &str =",
        f"    {_rust_string(document['operationsSha256'])};",
        "",
        f"pub const EVENT_READ_GUARD_CONTRACT: &str = {_rust_string(document['eventReadGuardContract'])};",
        f"pub const EVENT_READ_GUARD_SCOPED_CONTRACT: &str = {_rust_string(document['eventReadGuardScopedContract'])};",
        f"pub const EVENT_READ_GUARD_MAX_TYPES: usize = {document['eventReadGuardMaxTypes']};",
        "",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        "pub enum StorageOperationKind {",
        "    Query,",
        "    Command,",
        "    Maintenance,",
        "}",
        "",
        "impl StorageOperationKind {",
        "    pub const fn mutates_state(self) -> bool {",
        "        !matches!(self, Self::Query)",
        "    }",
        "}",
        "",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        "pub enum StorageOwnerScope {",
        "    HandlerEnforced,",
        "}",
        "",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        "pub struct StorageOperationMetadata {",
        "    pub name: &'static str,",
        "    pub domain: &'static str,",
        "    pub kind: StorageOperationKind,",
        "    pub receipt_required: bool,",
        "    pub transaction_timeout_millis: Option<u64>,",
        "    pub owner_scope: StorageOwnerScope,",
        "}",
        "",
        "pub static STORAGE_OPERATIONS: &[StorageOperationMetadata] = &[",
    ]
    for operation in document["operations"]:
        try:
            kind = kind_names[operation["kind"]]
        except KeyError as error:
            raise ValueError(f"unknown operation kind: {error.args[0]!r}") from error
        timeout = operation["transactionTimeoutSeconds"]
        if timeout is None:
            timeout_rust = "None"
        else:
            timeout_millis = float(timeout) * 1_000
            if (
                not math.isfinite(timeout_millis)
                or timeout_millis <= 0
                or not timeout_millis.is_integer()
            ):
                raise ValueError(f"invalid transaction timeout: {timeout!r}")
            timeout_rust = f"Some({int(timeout_millis)})"
        if operation["ownerScope"] != "handler-enforced":
            raise ValueError(f"unknown owner scope: {operation['ownerScope']!r}")
        lines.extend([
            "    StorageOperationMetadata {",
            f"        name: {_rust_string(operation['name'])},",
            f"        domain: {_rust_string(operation['domain'])},",
            f"        kind: StorageOperationKind::{kind},",
            f"        receipt_required: {str(operation['receiptRequired']).lower()},",
            f"        transaction_timeout_millis: {timeout_rust},",
            "        owner_scope: StorageOwnerScope::HandlerEnforced,",
            "    },",
        ])
    lines.extend([
        "];",
        "",
        "pub fn storage_operation(name: &str) -> Option<&'static StorageOperationMetadata> {",
        "    STORAGE_OPERATIONS",
        "        .binary_search_by_key(&name, |operation| operation.name)",
        "        .ok()",
        "        .map(|index| &STORAGE_OPERATIONS[index])",
        "}",
    ])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    document = _document()
    outputs = {
        JSON_OUTPUT: json.dumps(document, ensure_ascii=False, indent=2) + "\n",
        RUST_OUTPUT: _render_rust(document),
        PYTHON_OUTPUT: (
            '"""@generated by scripts/gen_storage_operation_catalog.py; do not edit."""\n'
            '\n# Source: sidecar schema.py and operation_domains registry.\n'
            f"STORAGE_SCHEMA_VERSION = {document['sourceSchemaVersion']}\n"
        ),
    }
    outputs[REPOSITORY_ROOT / "tofu_db" / "generated_contract.py"] = outputs[PYTHON_OUTPUT]
    if args.check:
        stale = [
            path.relative_to(REPOSITORY_ROOT)
            for path, rendered in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != rendered
        ]
        if stale:
            for path in stale:
                print(f"{path} is stale")
            print("run python3 scripts/gen_storage_operation_catalog.py")
            return 1
        return 0
    for path, rendered in outputs.items():
        path.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
