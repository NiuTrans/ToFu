#!/usr/bin/env python3
"""Generate the project coordination DTOs from the JSON Schema authority."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/project_coordination_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/project-coordination.generated.ts'
ROUTER_SOURCE = ROOT / 'contracts/router_v1.schema.json'
ROUTER_OUTPUT = ROOT / 'frontend/src/api/router.generated.ts'


def ts(schema, root=None):
    if '$ref' in schema:
        value = root
        for key in filter(None, schema['$ref'].removeprefix('#').split('/')):
            value = value[int(key)] if isinstance(value, list) else value[key]
        return ts(value, root)
    if 'anyOf' in schema or 'oneOf' in schema:
        return ' | '.join(ts(value, root) for value in schema.get('anyOf', schema.get('oneOf')))
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(ts({**schema, 'type': value}, root) for value in kind)
    if kind == 'null':
        return 'null'
    if kind == 'array':
        return '(' + ts(schema['items'], root) + ')[]'
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean'):
        return kind
    if kind == 'object':
        required = schema.get('required', [])
        return '{ ' + ' '.join(f'{key}{"" if key in required else "?"}: {ts(value, root)};'
                              for key, value in schema['properties'].items()) + ' }'
    raise ValueError(f'Unsupported coordination schema: {schema}')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    content = '// Generated by scripts/gen_project_coordination_contract.py; do not edit.\n'
    content += 'export type CoordinationBinding = ' + ts(schema) + ';\n'
    content += 'export type CoordinationBindRequest = ' + ts(schema['$defs']['bindRequest']) + ';\n'

    content += 'export type CoordinationCreateRequest = ' + ts(schema['$defs']['createRequest']) + ';\n'

    for name, definition in [('CoordinatorConversationPage', 'conversationPage'),
                             ('CoordinatorReportState', 'reportState'),
                             ('CoordinatorReportReadRequest', 'reportReadRequest'),
                             ('CoordinatorProgressTask', 'progressTask'),
                             ('CoordinatorProgressBoard', 'progressBoard'),
                             ('CoordinatorProgressState', 'progressState')]:
        content += f'export type {name} = ' + ts(schema['$defs'][definition], schema) + ';\n'

    message_schema = json.loads((ROOT / 'contracts/project_messages_v1.json').read_text())
    content += 'export type ProjectMessageView = ' + ts(message_schema['$defs']['messageView'], message_schema) + ';\n'
    content += 'export type ProjectMessagePage = ' + ts(message_schema['$defs']['pageView'], message_schema) + ';\n'
    # The Global Router is a coordinator (docs/ROUTER.md); its wire DTOs share this generator.
    router_schema = json.loads(ROUTER_SOURCE.read_text())
    router = '// Generated by scripts/gen_project_coordination_contract.py; do not edit.\n'
    for name, definition in [('RouterState', 'routerState'),
                             ('RouterEnsureRequest', 'ensureRequest'),
                             ('RouterWorkerModelRequest', 'workerModelRequest'),
                             ('RouterInstruction', 'instruction'),
                             ('RouterInstructionApplication', 'instructionApplication'),
                             ('RouterInstructionPage', 'instructionPage'),
                             ('RouterInstructionDetail', 'instructionDetail'),
                             ('RouterInstructionCancelRequest', 'instructionCancelRequest'),
                             ('RouterInstructionPauseRequest', 'instructionPauseRequest'),
                             ('RouterInstructionResumeRequest', 'instructionResumeRequest'),
                             ('RouterWorkerModelQuery', 'workerModelQuery'),
                             ('RouterWatchdogState', 'watchdogState'),
                             ('RouterWatchdogReviewRequest', 'watchdogReviewRequest')]:
        router += f'export type {name} = ' + ts(router_schema['$defs'][definition], router_schema) + ';\n'
    for output, generated in ((OUTPUT, content), (ROUTER_OUTPUT, router)):
        if args.check:
            if not output.exists() or output.read_text() != generated:
                raise SystemExit(f'Coordination DTO drift: {output.relative_to(ROOT)}')
        else:
            output.write_text(generated)


if __name__ == '__main__':
    main()
