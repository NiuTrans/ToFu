#!/usr/bin/env python3
"""Package the canonical frontier schema for standalone agent-core consumers."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads((ROOT / 'contracts/execution_account_frontier_v1.schema.json').read_text())
    output = ('"""Generated by scripts/gen_execution_account_frontier.py; do not edit."""\n\n'
        + 'FORMAT = ' + repr(schema['$id']) + '\nSCHEMA = ' + pprint.pformat(schema, sort_dicts=False) + '\n')
    target = ROOT / 'lib/agent_core/account_frontier_contract.py'
    if args.check:
        if not target.is_file() or target.read_text() != output:
            raise SystemExit('Execution account frontier schema differs; regenerate')
    else:
        target.write_text(output)


if __name__ == '__main__':
    main()
