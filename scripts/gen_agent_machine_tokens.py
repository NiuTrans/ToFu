"""Generate TS sanitation and Rust patterns from the Python machine-token owner.

Entry point: main (write / --check). Only selected authority AST declarations
are evaluated with stdlib re; application imports and initialization never run.
"""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/agent_verdict/_handoff.py'
DECLARATIONS = {
    'VU_DONE_SENTINEL', '_PROGRESS_RE', '_VERDICT_RE',
    '_MACHINE_TOKEN_STRIP_PATTERNS', 'strip_machine_tokens',
}


def load_authority():
    """Load the registry and real strip function without importing the app."""
    tree = ast.parse(SOURCE.read_text(encoding='utf-8'), filename=str(SOURCE))
    selected = []
    for node in tree.body:
        if isinstance(node, ast.Assign):
            names = {target.id for target in node.targets if isinstance(target, ast.Name)}
            if names & DECLARATIONS:
                selected.append(node)
        elif isinstance(node, ast.FunctionDef) and node.name == 'strip_machine_tokens':
            selected.append(node)
    namespace = {'re': re}
    exec(compile(ast.Module(body=selected, type_ignores=[]), str(SOURCE), 'exec'), namespace)
    if not DECLARATIONS <= namespace.keys():
        raise ValueError('Machine-token authority declarations changed; update generator')
    return namespace


def character_class(predicate):
    """Freeze Python Unicode semantics, independent of JS/Rust Unicode versions."""
    ranges = []
    start = end = None
    for code in range(sys.maxunicode + 1):
        if predicate(chr(code)):
            if start is None:
                start = end = code
            elif code == end + 1:
                end = code
            else:
                ranges.append((start, end))
                start = end = code
    if start is not None:
        ranges.append((start, end))
    def escape(code):
        return rf'\u{{{code:x}}}'
    return '[' + ''.join(escape(a) if a == b else escape(a) + '-' + escape(b)
                         for a, b in ranges) + ']'


def translate_pattern(pattern, ignore_case, whitespace, digits):
    """Translate the owner's limited portable regex dialect; reject unknown escapes.

    Unicode ignore-case differs for dotted/dotless I; both engines already fold
    long S and Kelvin K. Explicit I alternatives preserve Python's extra folds.
    """
    result = []
    index = 0
    while index < len(pattern):
        char = pattern[index]
        if char == '\\':
            index += 1
            escaped = pattern[index]
            if escaped == 's':
                result.append(whitespace)
            elif escaped == 'd':
                result.append(digits)
            elif escaped in '[](){}.*+?^$|\\':
                result.append('\\' + escaped)
            elif escaped == ' ':  # Python re.escape escapes literal space.
                result.append(' ')
            else:
                raise ValueError(f'Unsupported machine-token regex escape: {escaped!r}')
        elif ignore_case and char in 'iI':
            result.append('[iIİı]')
        else:
            result.append(char)
        index += 1
    return ''.join(result)


def render_outputs():
    authority = load_authority()
    whitespace = character_class(str.isspace)
    digits = character_class(str.isdecimal)
    header = ('// Generated by scripts/gen_agent_machine_tokens.py; do not edit.\n'
              '// Source: lib/agent_verdict/_handoff.py (_MACHINE_TOKEN_STRIP_PATTERNS).\n')
    ts = [header, 'const MACHINE_TOKEN_PATTERNS: readonly RegExp[] = [']
    rust = [header, 'pub(super) const MACHINE_TOKEN_PATTERNS: &[(&str, bool)] = &[']
    for label, regex in authority['_MACHINE_TOKEN_STRIP_PATTERNS']:
        if regex.flags & ~(re.UNICODE | re.IGNORECASE):
            raise ValueError(f'Unsupported regex flags for {label}')
        ignore_case = bool(regex.flags & re.IGNORECASE)
        pattern = translate_pattern(regex.pattern, ignore_case, whitespace, digits)
        ts.append(f'  new RegExp({json.dumps(pattern, ensure_ascii=False)}, "g{"i" if ignore_case else ""}u"),')
        rust.append(f'    (r#"{pattern}"#, {str(ignore_case).lower()}),')
    ts.extend([
        '];', '',
        '// Python strip() whitespace, not ECMAScript trim() (which also strips BOM).',
        f'const OUTER_WHITESPACE = new RegExp({json.dumps("^" + whitespace + "+|" + whitespace + "+$", ensure_ascii=False)}, "gu");',
        '', 'export function stripAgentMachineTokens(text: string): string {',
        '  let out = text;',
        '  for (const pattern of MACHINE_TOKEN_PATTERNS) out = out.replace(pattern, \'\');',
        '  return out === text ? text : out.replace(/\\n{3,}/g, \'\\n\\n\').replace(OUTER_WHITESPACE, \'\');',
        '}', '',
    ])
    rust.extend(['];', ''])
    return {
        ROOT / 'frontend/src/conversation/presentation/agent-machine-tokens.generated.ts': '\n'.join(ts),
        ROOT / 'packages/tofu-db/src/turn/agent_machine_tokens.generated.rs': '\n'.join(rust),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in render_outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        parser.error('Machine-token outputs are stale: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
