#!/usr/bin/env python3
"""Freeze the linked ICU default simple-case-fold table for Tofu-DB."""

from __future__ import annotations

import argparse
import ctypes
import ctypes.util
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages" / "tofu-db" / "src" / "generated_unicode_simple_fold.rs"


def _icu_symbol(library: ctypes.CDLL, base: str):
    """Resolve unversioned or ELF/macOS version-suffixed ICU exports."""
    candidates = [base]
    library_name = str(library._name)  # noqa: SLF001 - ctypes exposes no public name
    versions = [int(value) for value in re.findall(r"(?:so\.|\.)(\d+)", library_name)]
    candidates.extend(f"{base}_{version}" for version in versions)
    candidates.extend(f"{base}_{version}" for version in range(99, 49, -1))
    for candidate in dict.fromkeys(candidates):
        try:
            return getattr(library, candidate)
        except AttributeError:
            continue
    raise RuntimeError(f"linked ICU library does not export {base}")


def _load_icu() -> ctypes.CDLL:
    """Load the libicuuc the legacy authority's _sqlite3 actually links.

    find_library("icuuc") resolves the OS ICU (Unicode 6.2 on this host),
    while the conda libsqlite3 behind the storage authority links the conda
    ICU (78 / Unicode 17) — folding must be frozen from the latter.
    """
    import _sqlite3  # noqa: PLC0415 - resolves the interpreter's own build
    import subprocess  # noqa: PLC0415

    ldd = subprocess.run(
        ["ldd", _sqlite3.__file__], check=True, capture_output=True, text=True
    ).stdout
    match = re.search(r"libicuuc\.so\.\d+ => (\S+)", ldd)
    if not match:
        raise RuntimeError("_sqlite3 dependency chain has no libicuuc")
    return ctypes.CDLL(match.group(1))


def _render() -> str:
    library = _load_icu()
    fold = _icu_symbol(library, "u_foldCase")
    fold.argtypes = [ctypes.c_int32, ctypes.c_uint32]
    fold.restype = ctypes.c_int32
    unicode_version = (ctypes.c_uint8 * 4)()
    get_unicode_version = _icu_symbol(library, "u_getUnicodeVersion")
    get_unicode_version.argtypes = [ctypes.POINTER(ctypes.c_uint8)]
    get_unicode_version.restype = None
    get_unicode_version(unicode_version)

    mappings = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        mapped = int(fold(codepoint, 0))  # U_FOLD_CASE_DEFAULT
        if mapped != codepoint:
            mappings.append((codepoint, mapped))
    version = tuple(int(value) for value in unicode_version[:3])
    rows = [f"    (0x{source:06X}, 0x{target:06X})," for source, target in mappings]
    return "\n".join([
        "//! @generated by scripts/gen_tofudb_unicode_simple_fold.py; do not edit.",
        "",
        "/// ICU default simple case folding used by SQLite ENABLE_ICU LIKE.",
        "#[cfg(test)]",
        f"pub(crate) const ICU_UNICODE_VERSION: (u8, u8, u8) = {version!r};",
        "#[cfg(test)]",
        f"pub(crate) const SIMPLE_CASE_FOLDING_COUNT: usize = {len(mappings)};",
        "pub(crate) const SIMPLE_CASE_FOLDING: &[(u32, u32)] = &[",
        *rows,
        "];",
        "",
        "pub(crate) fn simple_case_fold(codepoint: u32) -> u32 {",
        "    SIMPLE_CASE_FOLDING",
        "        .binary_search_by_key(&codepoint, |entry| entry.0)",
        "        .map(|index| SIMPLE_CASE_FOLDING[index].1)",
        "        .unwrap_or(codepoint)",
        "}",
        "",
        "// --check detects linked-ICU Unicode-data drift.",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = _render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale for the linked ICU")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
