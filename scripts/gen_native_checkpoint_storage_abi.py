"""Generate the private checkpoint storage ABI and its synchronous FFI binding."""
import argparse
import json
from pathlib import Path
import pprint
import tempfile
import sys

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    import cffi
    sys.path.insert(0, str(ROOT))
    from lib.native_binary import MEMFD_CDEF
    spec = json.loads((ROOT / 'contracts/native_checkpoint_storage_abi_v1.json').read_text())
    declarations = [spec['callback_declaration']]
    for name, arguments in spec['signatures'].items():
        declarations.append('uint32_t ' + name + '(' + (
            ', '.join(kind + ' ' + field for kind, field in arguments) or 'void') + ');')
    cdef = '\n'.join(declarations) + '\n'
    builder = cffi.FFI()
    builder.cdef(cdef + MEMFD_CDEF)
    builder.set_source('lib.storage_authority_sql.generated_checkpoint_storage_cffi', None)
    with tempfile.TemporaryDirectory() as temporary:
        generated = Path(builder.compile(tmpdir=temporary)).read_text()
    rust = ['//! Generated by gen_native_checkpoint_storage_abi.py; do not edit.',
            f"pub const ABI_VERSION: u32 = {spec['abi_version']};",
            f"pub const ENVELOPE_BYTES: usize = {spec['envelope_bytes']};",
            f"pub const REQUEST_DOCUMENT_SLOTS: usize = {spec['request_document_slots']};",
            f"pub const REQUEST_IDENTITY_ESCAPE_SLOTS: usize = {spec['request_identity_escape_slots']};",
            'pub const FORMAT: &str = ' + json.dumps(spec['callback_format']) + ';']
    rust += [f'pub const STATUS_{key.upper()}: u32 = {value};'
             for key, value in spec['statuses'].items()]
    return {
        'contracts/native_checkpoint_storage_abi_v1.h':
            '// Generated by gen_native_checkpoint_storage_abi.py; do not edit.\n'
            '#include <stdint.h>\n#include <stddef.h>\n' + cdef,
        'packages/tofu-runtime/src/generated_checkpoint_storage_abi.rs': '\n'.join(rust) + '\n',
        'lib/native_binary/generated_checkpoint_storage_contract.py':
            '"""Generated by gen_native_checkpoint_storage_abi.py; do not edit."""\nSPEC = '
            + pprint.pformat(spec, sort_dicts=False, width=100) + '\n',
        'lib/storage_authority_sql/generated_checkpoint_storage_contract.py':
            '"""Generated compatibility import; do not edit."""\n'
            'from lib.native_binary.generated_checkpoint_storage_contract import SPEC as SPEC\n',
        'lib/storage_authority_sql/generated_checkpoint_storage_cffi.py':
            '# Generated by gen_native_checkpoint_storage_abi.py; do not edit.\n' + generated,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('native checkpoint storage ABI drift: ' + name)
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
