#!/usr/bin/env python3
"""Generate native loop directives and constants from the retained policy owner."""
import argparse
import ast
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def outputs():
 values={}
 for name in ('lib/orchestration/loop_policy.py','lib/orchestration/loop_runtime.py','lib/agent_verdict/_stuck.py','lib/agent_verdict/_handoff.py','lib/agent_verdict/_config.py'):
  for node in ast.parse((ROOT/name).read_text()).body:
   if isinstance(node,ast.Assign) and len(node.targets)==1 and isinstance(node.targets[0],ast.Name):
    try:values[node.targets[0].id]=ast.literal_eval(node.value)
    except (ValueError,TypeError):pass
 lines=['// Generated by scripts/gen_native_loop_policy.py; do not edit.']
 for name in ('MAX_REPLANS','MAX_ZERO_DELIVERABLE_TURNS','GOAL_BLOCKED_MIN_JUSTIFICATION_CHARS','AUTOPILOT_STUCK_WINDOW'):
  lines.append(f'pub const {name}: u64 = {values[name]};')
 for name in ('STUCK_JACCARD','DIMINISHING_TARGET_OVERLAP'):
  lines.append(f'pub const {name}: f64 = {values[name]};')
 if values['DIMINISHING_MIN_RESOLVED']!=1:raise SystemExit('review native progress sum before changing min_resolved')
 for name,value in values.items():
  if name.endswith('_DIRECTIVE'):lines.append(f'pub const {name}: &str = '+json.dumps(value,ensure_ascii=False)+';')
 return {ROOT/'packages/tofu-runtime/src/generated_loop_policy.rs':'\n'.join(lines)+'\n'}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 for path,text in outputs().items():
  if args.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit('native loop generation drift: '+str(path))
  else:path.write_text(text)
if __name__=='__main__':main()
