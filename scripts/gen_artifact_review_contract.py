"""Generate artifact review DTOs from the canonical schema; --check detects drift."""
import argparse
import json
from pathlib import Path
from json_schema_types import ts_type

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/artifact_review_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/artifact-review.generated.ts'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    content = '// Generated by scripts/gen_artifact_review_contract.py; do not edit.\n'
    content += 'export const ARTIFACT_REVIEW_MAX_FACT_BINDINGS = ' + str(
        schema['$defs']['ArtifactDecisionCommand']['properties']['factBindings']['maxItems']) + ';\n\n'
    for name, rule in schema['$defs'].items():
        content += f'export type {name} = {ts_type(rule)};\n\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Artifact review contract drift')
    else:
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
