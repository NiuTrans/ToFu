"""Package shared stdlib resource and process owners for independent search.

Only the declared owners below are maintained. Generated copies cannot import
the host application and carry exact source hashes. --check is read-only.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNERS = {
    'tofu_workers/resources.py': 'generated_resources.py',
    'lib/project_mod/process_group.py': 'generated_process_groups.py',
    'lib/paper/builds/pdf_validation_limits.py': 'generated_process_lifetime.py',
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for source, name in OWNERS.items():
        data = (ROOT / source).read_bytes()
        header = (f'# Generated by scripts/gen_packaged_search_runtime.py; do not edit.\n'
                  f'# Authority: {source} (MIT); copyright (c) 2026 Tofu contributors.\n'
                  f'# Source SHA256: {hashlib.sha256(data).hexdigest()}\n')
        expected = header.encode() + data
        output = ROOT / 'packages/tofu-search/tofu_search' / name
        if args.check:
            if not output.is_file() or output.read_bytes() != expected:
                stale.append(name)
        else:
            output.write_bytes(expected)
    if stale:
        raise SystemExit('Run scripts/gen_packaged_search_runtime.py: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
