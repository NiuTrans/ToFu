#!/usr/bin/env python3
"""Derive browser dispatch DTOs from the project dispatch JSON Schema authority."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/project_dispatch_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/project-dispatch.generated.ts'


def ts(schema, root):
    if 'anyOf' in schema:
        return ' | '.join(ts(value, root) for value in schema['anyOf'])
    if '$ref' in schema:
        value = root
        for key in schema['$ref'].removeprefix('#/').split('/'):
            value = value[key]
        return ts(value, root)
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(ts({**schema, 'type': value}, root) for value in kind)
    if kind == 'null':
        return 'null'
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean'):
        return kind
    if kind == 'array':
        return '(' + ts(schema['items'], root) + ')[]'
    if kind == 'object':
        if 'properties' not in schema:
            return 'Record<string, unknown>'
        required = schema.get('required', [])
        return '{ ' + ' '.join(f'{key}{"" if key in required else "?"}: {ts(value, root)};'
                              for key, value in schema['properties'].items()) + ' }'
    raise ValueError(f'Unsupported dispatch schema: {schema}')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    content = '// Generated by scripts/gen_project_dispatch_contract.py; do not edit.\n'
    limits = {key: {field: value[field] for field in ('minimum', 'maximum')}
              for key, value in schema['$defs']['coordinatorBudgetSettings']['properties'].items()}
    content += 'export const COORDINATOR_BUDGET_LIMITS = ' + json.dumps(limits) + ' as const;\n'
    for name, definition in [('ProjectDispatchRequest', 'request'),
                             ('ProjectDispatchListQuery', 'listQuery'),
                             ('CoordinatorBudgetSettings', 'coordinatorBudgetSettings'),
                             ('CoordinatorBudgetState', 'coordinatorBudgetState'),
                             ('CoordinatorBudgetUpdate', 'coordinatorBudgetUpdate'),

                             ('ProjectDispatchBatchRequest', 'batchRequest'),
                             ('ProjectDispatchBatchRetry', 'batchRetry'),
                             ('ProjectDispatchBatchView', 'batchView'),
                             ('ProjectDispatchProfile', 'profile'),
                             ('ProjectDispatchReworkOf', 'reworkOf'),

                             ('ProjectDispatchDependency', 'dependency'),
                             ('ProjectDispatchDependencyState', 'dependencyState'),
                             ('ProjectDispatchPublishRequest', 'publishRequest'),
                             ('ProjectDispatchAdmission', 'admission'),
                             ('ProjectDispatchRetry', 'retry'),
                             ('ProjectDispatchRevoke', 'revoke'),
                             ('ProjectDispatchReviewRequest', 'reviewRequest'),
                             ('ProjectDispatchView', 'view')]:
        content += f'export type {name} = {ts(schema["$defs"][definition], schema)};\n'
    content += f'export type ProjectDispatchPage = {ts(schema["$defs"]["historyPage"], schema)};\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Project dispatch DTO drift')
    else:
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
