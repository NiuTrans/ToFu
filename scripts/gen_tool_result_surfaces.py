#!/usr/bin/env python3
"""Generate Python and TypeScript result surface policy from one JSON authority."""
import argparse
import json
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    value = json.loads((ROOT / 'contracts/tool_result_surfaces_v1.json').read_text())
    assert value['contractVersion'] == 'tofu.tool-result-surfaces/v1'
    assert set(value['defaultPolicy']) == {'modelFormat', 'frontendFormat', 'reason'}
    for policy in [value['defaultPolicy'], *value['toolPolicies'].values()]:
        assert policy['modelFormat'] in {'producer', 'agent_report', 'agent_report_sections',
                                          'spawn_receipt', 'artifact_query', 'gateway_results'}
        assert policy['frontendFormat'] in {'verbatim', 'report'}
    header = 'Generated by scripts/gen_tool_result_surfaces.py; do not edit.'
    return {
        ROOT / 'lib/tools/result_surfaces_generated.py':
            f'"""{header}"""\nCONTRACT = ' + pformat(value, sort_dicts=False) + '\n',
        ROOT / 'frontend/src/conversation/presentation/tool-result-surfaces.generated.ts':
            f'/** {header} */\nexport const TOOL_RESULT_SURFACES = '
            + json.dumps(value, ensure_ascii=False, indent=2) + ' as const;\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print('Stale result surface policy: ' + ', '.join(stale))
        return 1
    print('Tool result surface policy: OK')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
