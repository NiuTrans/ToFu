#!/usr/bin/env python3
"""Derive authenticated worker transport constants from its single contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = json.loads((ROOT / 'contracts/worker_control_v1.json').read_text())
    constants = {'FORMAT': spec['format'], 'WATCH_OPERATION': spec['operation']}
    python = '"""Generated by scripts/gen_worker_control.py; do not edit."""\n\n'
    python += ''.join(f'{name} = {value!r}\n' for name, value in constants.items())
    rust = '// Generated by scripts/gen_worker_control.py; do not edit.\n'
    rust += ''.join(f'pub(crate) const {name}: &str = {json.dumps(value)};\n'
                    for name, value in constants.items())
    for name, content in (
        ('lib/storage/generated_worker_control.py', python),
        ('packages/tofu-db/src/generated_worker_control.rs', rust),
    ):
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'Worker control generated file differs: {name}')
        else:
            target.write_text(content)


if __name__ == '__main__':
    main()
