#!/usr/bin/env python3
"""Derive authenticated worker transport constants from its single contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = json.loads((ROOT / 'contracts/worker_control_v1.json').read_text())
    conversation = json.loads((ROOT / 'contracts/conversation_control_v1.json').read_text())
    constants = {'FORMAT': spec['format'], 'WATCH_OPERATION': spec['operation'],
                 'CONVERSATION_FORMAT': conversation['format'],
                 'CONVERSATION_WATCH_OPERATION': conversation['operation']}
    python = '"""Generated by scripts/gen_worker_control.py; do not edit."""\n\n'
    python += ''.join(f'{name} = {value!r}\n' for name, value in constants.items())
    rust = '// Generated by scripts/gen_worker_control.py; do not edit.\n'
    rust += ''.join(f'pub(crate) const {name}: &str = {json.dumps(value)};\n'
                    for name, value in constants.items())
    cdef = '\n'.join(spec['embeddedAbi']['declarations']) + '\n'
    abi_python = '"""Generated by scripts/gen_worker_control.py; do not edit."""\n\n'
    abi_python += f'CDEF = {cdef!r}\n'
    abi_header = '// Generated by scripts/gen_worker_control.py; do not edit.\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n' + cdef
    for name, content in (
        ('lib/storage/generated_worker_control.py', python),
        ('packages/tofu-db/src/generated_worker_control.rs', rust),
        ('tofu_db/generated_commit_watch.py', abi_python),
        ('contracts/native_commit_watch_abi_v1.h', abi_header),
    ):
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'Worker control generated file differs: {name}')
        else:
            target.write_text(content)


if __name__ == '__main__':
    main()
