#!/usr/bin/env python3
"""Derive browser continuity DTOs from sibling-owned schema definitions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {'ProjectScopeChange': 'project_scope_change_v1.schema.json',
           'ProjectResponsibility': 'project_responsibility_v1.schema.json',
           'ProjectSharedFiles': 'project_shared_files_v1.schema.json'}
OUTPUT = ROOT / 'frontend/src/api/project-continuity.generated.ts'


def ts(schema, source):
    if '$ref' in schema:
        filename, _, fragment = schema['$ref'].partition('#')
        target = ROOT / 'contracts' / filename if filename else source
        value = json.loads(target.read_text())
        for key in fragment.removeprefix('/').split('/'):
            if key:
                value = value[int(key)] if isinstance(value, list) else value[key]
        return ts(value, target)
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return ' | '.join(ts(value, source) for value in schema[union])
    if 'allOf' in schema and 'type' not in schema:
        return ' & '.join(ts(value, source) for value in schema['allOf'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(ts({**schema, 'type': value}, source) for value in kind)
    if kind == 'null':
        return 'null'
    if kind in ('number', 'integer'):
        return 'number'
    if kind in ('string', 'boolean'):
        return kind
    if kind == 'array':
        return '(' + ts(schema['items'], source) + ')[]'
    if kind == 'object':
        if 'properties' not in schema:
            additional = schema.get('additionalProperties')
            return 'Record<string, ' + (ts(additional, source) if isinstance(additional, dict) else 'unknown') + '>'
        required = schema.get('required', [])
        return '{ ' + ' '.join(f'{json.dumps(key)}{"" if key in required else "?"}: {ts(value, source)};'
                              for key, value in schema['properties'].items()) + ' }'
    # Validation-only branches (required/not/bounds) add no TypeScript shape.
    if kind is None:
        return 'unknown'
    raise ValueError(f'Unsupported schema in {source.name}: {schema}')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = '// Generated by scripts/gen_project_continuity_contract.py; do not edit.\n'
    for prefix, filename in SOURCES.items():
        source = ROOT / 'contracts' / filename
        schema = json.loads(source.read_text())
        if prefix == 'ProjectScopeChange':
            limit = schema['$defs']['request']['properties']['targets']['maxItems']
            content += f'export const PROJECT_SCOPE_TARGET_LIMIT = {limit};\n'
        for name, definition in schema['$defs'].items():
            suffix = ''.join(part[:1].upper() + part[1:] for part in name.replace('_', '-').split('-'))
            content += f'export type {prefix}{suffix} = {ts(definition, source)};\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Project continuity DTO drift')
    else:
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
