#!/usr/bin/env python3
"""Freeze CPython storage.v1 ``str.casefold`` semantics for Tofu-DB."""

from __future__ import annotations

import argparse
from pathlib import Path
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages" / "tofu-db" / "src" / "generated_unicode_casefold.rs"


def _rust_string(value: str) -> str:
    return '"' + "".join(f"\\u{{{ord(char):x}}}" for char in value) + '"'


def _render() -> str:
    mappings = []
    digit_ranges: list[tuple[int, int]] = []
    digit_start: int | None = None
    digit_end: int | None = None
    for codepoint in range(0x110000):
        char = chr(codepoint)
        folded = char.casefold()
        if folded != char:
            mappings.append(
                f"        '\\u{{{codepoint:x}}}' => Some({_rust_string(folded)}),"
            )
        if char.isdigit():
            if digit_start is None:
                digit_start = digit_end = codepoint
            elif codepoint == digit_end + 1:
                digit_end = codepoint
            else:
                digit_ranges.append((digit_start, digit_end))
                digit_start = digit_end = codepoint
    if digit_start is not None:
        digit_ranges.append((digit_start, digit_end))
    digit_patterns = [
        f"        '\\u{{{start:x}}}'..='\\u{{{end:x}}}'"
        if start != end
        else f"        '\\u{{{start:x}}}'"
        for start, end in digit_ranges
    ]
    version = tuple(int(part) for part in unicodedata.unidata_version.split("."))
    version = version + (0,) * (3 - len(version))
    return "\n".join([
        "//! @generated by scripts/gen_tofudb_unicode_casefold.py; do not edit.",
        "",
        f"pub const PYTHON_UNICODE_CASEFOLD_VERSION: (u16, u16, u16) = ({version[0]}, {version[1]}, {version[2]});",
        f"pub const PYTHON_UNICODE_CASEFOLD_MAPPING_COUNT: usize = {len(mappings)};",
        "",
        "pub fn full_casefold_mapping(value: char) -> Option<&'static str> {",
        "    match value {",
        *mappings,
        "        _ => None,",
        "    }",
        "}",
        "",
        "pub fn python_is_digit(value: char) -> bool {",
        "    matches!(value,",
        "        " + "\n        | ".join(pattern.strip() for pattern in digit_patterns),
        "    )",
        "}",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = _render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
