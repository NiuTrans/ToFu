#!/usr/bin/env python3
"""Import exact pinned tiktoken-rs rank data into native source identity.

Input --source-dir is tiktoken-rs 0.11.0's assets directory. Exact SHA-256 and
rank count refuse changed data; no download or runtime cache path is inferred.
Generated Rust data stays in the native crate's existing source closure.
"""
import argparse
import base64
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TABLES={
    'cl100k_base':('223921b76ee99bde995b7ff738513eef100fb51d18c93597a113bcffe865b2a7',100256),
    'o200k_base':('446a9538cb6c348e3516120d7c08b09f57c36495e2acfffe59a5bf8b0cfb1a2d',199998),
}


def generate(source_dir,check=False):
    for name,(expected,count) in TABLES.items():
        raw=(source_dir/(name+'.tiktoken')).read_bytes()
        if hashlib.sha256(raw).hexdigest()!=expected or len(raw.splitlines())!=count:
            raise ValueError('Pinned token rank asset differs: '+name)
        text=raw.decode('ascii')
        packed=bytearray();maximum=0;seen=set()
        for ordinal,line in enumerate(raw.splitlines()):
            encoded,rank=line.split(b' ')
            token=base64.b64decode(encoded,validate=True)
            if (not token or len(token)>65535 or rank!=str(ordinal).encode('ascii') or token in seen
                    or base64.b64encode(token)!=encoded):
                raise ValueError('Pinned token structure differs: '+name)
            seen.add(token);maximum=max(maximum,len(token))
            packed.extend(len(token).to_bytes(2,'little'));packed.extend(token)
        if any(bytes([value]) not in seen for value in range(256)):
            raise ValueError('Pinned single-byte tokens missing: '+name)
        packed_text=''.join('\\x'+format(value,'02x') for value in packed)
        result=('// Generated by scripts/gen_native_token_rank_tables.py; do not edit.\n'
                '// Source: tiktoken-rs 0.11.0 assets/'+name+'.tiktoken.\n'
                '// MIT notices: licenses/tiktoken-rs-0.11.0/{LICENSE,LICENSE-openai-tiktoken}.\n'
                'pub const SHA256: &str = "'+expected+'";\n'
                'pub const TOKEN_COUNT: usize = '+str(count)+';\n'
                'pub const MAX_TOKEN_BYTES: usize = '+str(maximum)+';\n'
                'pub const PACKED_SHA256: &str = "'+hashlib.sha256(packed).hexdigest()+'";\n'
                'pub static PACKED: &[u8] = b"'+packed_text+'";\n'
                '#[cfg(test)]\npub const DATA: &str = r#"'+text+'"#;\n')
        target=ROOT/'packages/tofu-runtime/src/token_ranks'/(name+'.rs')
        if check:
            if not target.exists() or target.read_text()!=result:
                raise ValueError('Generated token rank drift: '+name)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_text(result)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir',type=Path,required=True)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();generate(args.source_dir,args.check)
