#!/usr/bin/env node
/** Locked KaTeX delivery for standalone artifacts and report exports.
 * Entry: syncFrontendVendorAssets, CLI --check/--write. Dependencies: Node fs,
 * package-lock.json, its installed KaTeX, and the authored artifact adapter.
 * Capture all inputs before replacing outputs; never remove unowned files.
 */
import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(import.meta.dirname, '..');
const adapterSource = 'frontend/src/artifacts/math-auto-render.js';
const generatedNotice = '// Generated by scripts/frontend_vendor_assets.mjs; edit ' + adapterSource + '.\n';
const digest = (algorithm, bytes, encoding) => createHash(algorithm).update(bytes).digest(encoding);

async function collectOutputs(root) {
  const lock = JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8'));
  const packageRoot = join(root, 'node_modules/katex');
  const installed = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
  const version = lock.packages?.['node_modules/katex']?.version;
  if (typeof version !== 'string' || installed.version !== version) {
    throw new Error('Installed KaTeX differs from package-lock.json; run npm ci first.');
  }
  const outputs = new Map();
  const cdnAssets = {};
  for (const [name, source, destination] of [
    ['renderer', 'dist/katex.min.js', 'katex.min.js'],
    ['stylesheet', 'dist/katex.min.css', 'katex.min.css'],
    ['auto_render', 'dist/contrib/auto-render.min.js', null],
  ]) {
    const bytes = await readFile(join(packageRoot, source));
    cdnAssets[name] = {
      url: `https://cdn.jsdelivr.net/npm/katex@${version}/${source}`,
      integrity: 'sha384-' + digest('sha384', bytes, 'base64'),
    };
    if (destination) outputs.set(`static/vendor/katex/${destination}`, bytes);
  }
  const css = outputs.get('static/vendor/katex/katex.min.css').toString('utf8');
  const fonts = new Set();
  for (const match of css.matchAll(/url\(([^)]+)\)/g)) {
    const path = match[1].trim().replace(/^['"]|['"]$/g, '');
    if (!/^fonts\/[A-Za-z0-9_-]+\.(woff2?|ttf)$/.test(path)) {
      throw new Error(`KaTeX stylesheet has an unsupported asset reference: ${path}`);
    }
    fonts.add(path);
  }
  if (!fonts.size) throw new Error('KaTeX stylesheet has no font references.');
  const fontRows = await Promise.all([...fonts].sort().map(async (path) =>
    [`static/vendor/katex/${path}`, await readFile(join(packageRoot, 'dist', path))]));
  for (const [path, bytes] of fontRows) outputs.set(path, bytes);
  outputs.set('static/vendor/katex/LICENSE', await readFile(join(packageRoot, 'LICENSE')));
  outputs.set('static/vendor/katex/tofu-auto-render.js', Buffer.concat([
    Buffer.from(generatedNotice), await readFile(join(root, adapterSource)),
  ]));
  const staticHashes = Object.fromEntries([...outputs].map(([path, bytes]) =>
    [path, digest('sha256', bytes, 'hex')]));
  const metadata = '"""Generated by scripts/frontend_vendor_assets.mjs; do not edit.\n'
    + 'Locked math version, CDN integrity and standalone delivery byte identities.\n"""\n\n'
    + `KATEX_VERSION = ${JSON.stringify(version)}\n\n`
    + `KATEX_CDN_ASSETS = ${JSON.stringify(cdnAssets, null, 4)}\n\n`
    + `KATEX_STATIC_SHA256 = ${JSON.stringify(staticHashes, null, 4)}\n`;
  outputs.set('lib/http_transport/generated_frontend_vendor.py', Buffer.from(metadata));
  return outputs;
}

async function existingBytes(path) {
  try { return await readFile(path); }
  catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

async function replaceFile(path, bytes) {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.generate-${randomUUID()}`;
  try {
    await writeFile(temporary, bytes, { flag: 'wx' });
    await rename(temporary, path);
  } finally {
    await rm(temporary, { force: true });
  }
}

export async function syncFrontendVendorAssets({ root = repositoryRoot, write = false } = {}) {
  const outputs = await collectOutputs(root);
  const drift = [];
  for (const [relative, bytes] of outputs) {
    const path = join(root, relative);
    if ((await existingBytes(path))?.equals(bytes)) continue;
    if (write) await replaceFile(path, bytes);
    else drift.push(relative);
  }
  if (drift.length) {
    throw new Error('Frontend vendor artifacts differ; run npm run generate:vendor:\n' + drift.join('\n'));
  }
  return { files: outputs.size };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !['--check', '--write'].includes(args[0])) {
    console.error('Usage: node scripts/frontend_vendor_assets.mjs --check|--write');
    process.exitCode = 1;
  } else {
    syncFrontendVendorAssets({ write: args[0] === '--write' }).then(
      ({ files }) => console.log(`frontend vendor assets: ${files} files verified`),
      (error) => { console.error(error.message); process.exitCode = 1; },
    );
  }
}
