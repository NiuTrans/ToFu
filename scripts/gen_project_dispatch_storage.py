#!/usr/bin/env python3
"""Generate the SQL/application and native segmented dispatch storage contract."""
import argparse
import json
from pathlib import Path
import pprint
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = json.loads((ROOT / 'contracts/project_dispatch_storage_v2.json').read_text())
    if (spec['format'] != 'tofu.project-dispatch-storage/v2'
            or set(spec['namespaces']) != {'heads', 'documents'}
            or len(set(spec['namespaces'].values())) != 2
            or any(not re.fullmatch(r'[a-z0-9.]{1,128}', name) for name in spec['namespaces'].values())
            or len(spec['collections']) != len(set(spec['collections']))
            or 'indexes' not in spec['collections']
            or any(not re.fullmatch(r'[a-z_]{1,32}', name) for name in spec['collections'])
            or any(type(value) is not int or value <= 0 for value in spec['limits'].values())):
        raise ValueError('Invalid segmented dispatch storage contract')
    limits = spec['limits']
    if not (limits['indexBytes'] <= limits['headBytes'] <= limits['documentBytes'] <= limits['commitBytes']
            and limits['identityCharacters'] <= 256 and limits['maximumRevision'] < 2**53 - 1):
        raise ValueError('Inconsistent dispatch wire bounds')
    python = ('"""Generated by scripts/gen_project_dispatch_storage.py; do not edit."""\n'
              + 'SPEC = ' + pprint.pformat(spec, sort_dicts=False, width=100) + '\n')
    rust = ['//! Generated by scripts/gen_project_dispatch_storage.py; do not edit.',
            f'pub const FORMAT: &str = {json.dumps(spec["format"])};']
    for name, value in spec['namespaces'].items():
        rust.append(f'pub const {name.upper()}: &str = {json.dumps(value)};')
    rust.append('pub const COLLECTIONS: &[&str] = &[' + ', '.join(map(json.dumps, spec['collections'])) + '];')
    for name, value in spec['limits'].items():
        constant = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()
        rust.append(f'pub const {constant}: usize = {value};')
    outputs = {
        ROOT / 'lib/storage/generated_project_dispatch_contract.py': python,
        ROOT / 'packages/tofu-db/src/generated_project_dispatch_storage.rs': '\n'.join(rust) + '\n',
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Generated file is stale: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
