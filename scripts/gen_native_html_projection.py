"""Derive native HTML vocabulary and parity fixtures from the Python owner.

The observed standard-library tokenizer version is explicit. This generator does
not silently declare other Python tokenizer versions equivalent. No app, store,
provider or external page is loaded; fixtures contain synthetic text only.
"""
