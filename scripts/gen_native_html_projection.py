ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def rust_string(value):
    parts = []
    for ch in value:
        if ch in '\\"': parts.append('\\'+ch)
        elif 32 <= ord(ch) < 127: parts.append(ch)
        else: parts.append('\\u{'+format(ord(ch),'x')+'}')
    return '"'+''.join(parts)+'"'


@functools.lru_cache(maxsize=1)
def casing_tables():
    lower = [(i,chr(i).lower()) for i in range(sys.maxunicode+1) if chr(i).lower()!=chr(i)]
    flags = {}
    for name in ['Cased','CaseIgnorable']:
        function = getattr(ctypes.pythonapi,'_PyUnicode_Is'+name)
        function.argtypes = [ctypes.c_uint]
        function.restype = ctypes.c_int
        ranges = []
        for i in range(sys.maxunicode+1):
            if not function(i): continue
            if ranges and ranges[-1][1]+1 == i: ranges[-1][1] = i
            else: ranges.append([i,i])
        flags[name] = ranges
    return lower, flags


def cases(seed=20261015, count=2048):
    from lib.knowledge.html_text import _ENTITIES
    yield ''
    yield '<h1>A <i>B</i></h1><p>中文</p>'
    yield '<table><tr><td>outer<table><tr><td>inner</td></tr></table>end</td></tr></table>'
    yield '<h1>outer<h2>inner</h2>end</h1>'
    yield '<a b= "unterminated>tail'
    for code, lowered in casing_tables()[0]:
        yield '<X'+chr(code)+'><h1>a</X'+lowered+'>b</h1>c'
    for name in ['XΣ','XΣ:','XΣ\u0345','XΣ\u0345A','XΣ\u1c89','X\u1c89']:
        yield '<'+name+'><h1>a</'+name.lower()+'>b</h1>c'
    # U+1C89/1C8A gained case mappings after this Python Unicode profile.
    yield '<X\u1c89><h1>a</X\u1c8a>b</h1>c'
    yield '<div>'*5000+'tail'+'</orphan>'*5000
    yield '<pre><textarea> \n'+'<div>x'*1000+'</pre>tail'
    for name in _ENTITIES:
        yield '&'+name+';'
    for value in [0,1,9,10,13,31,32,127,*range(128,160),160,0xD7FF,0xD800,0xDFFF,0xE000,0x10FFFF,0x110000]:
        yield f'&#{value};&#x{value:x};'
    for raw in ['&','&a','&ab','&amp','&amp-','&amp.','&amp=','&bogus;','&#','&#1','&#1a;','&#1234x','&#xA','&#xAF;','&#bad;tail<h1>ok</h1>','&#'+'1'*4301+';','&#x'+'a'*5000+';']:
        yield raw
    for tag in ['script','style','template','svg','noscript','plaintext','xmp','iframe','noembed','noframes','textarea','title','div','pre','h1','tr','td','br','XΣ','XΣA','Xİ']:
        for ending in ['','>','/>',' a=1/>',' a="quoted >" >',' / x / >']:
            yield '<'+tag+ending+'a <b>inner &amp; text</b></'+tag+'>tail'
    for raw in ['<','</','</>','</ x>','<!--','<!-->','<!--->','<!-- --!>','a<![CDATA[b]]>c','a<![CDATA[b','<![x]>','<![x>','<!doctype x','<?x','<div x="unterminated>tail','<div x ="unterminated>tail','<a /"="x >tail','<div a="1"b=2>text','<div a=1/>x','<div/x>text','<a =x>text','<a\x00>text']:
        yield raw
    rng = random.Random(seed)
    tags = ['p','div','h1','h3','tr','td','th','b','i','br','pre','textarea','template','svg','noscript','script','title','xmp']
    text = ['alpha',' 中文 ',' \t\n ','&amp;','&notanentity;','&#128;','a|b','<&','<!--skip-->','\x1c','\u2003','\r\n','<![CDATA[x]]>','\x00']
    for _ in range(count):
        parts = []
        for _ in range(rng.randrange(1,40)):
            choice = rng.randrange(6); tag = rng.choice(tags)
            parts.append('<'+tag+'>' if choice == 0 else '</'+tag+'>' if choice == 1 else
                '<'+tag+rng.choice([' x=1>',' x="a>b"/>','/>','/q>',' x=\'a\'>']) if choice == 2 else rng.choice(text))
        yield ''.join(parts)


def oracle(seed=20261015, count=2048):
    from lib.knowledge.html_text import extract_html_text
    rows = []
    for value in cases(seed, count):
        try:
            row = dict(source=value, expected=extract_html_text(value))
        except ValueError:
            row = dict(source=value, error='numeric_reference')
        rows.append(row)
    return dict(format='tofu.python-html-projection-oracle/v1',
        python_version=sys.version.split()[0],
        tokenizer_sha256=hashlib.sha256(Path(html.parser.__file__).read_bytes()).hexdigest(),
        owner_sha256=hashlib.sha256((ROOT/'lib/knowledge/html_text.py').read_bytes()).hexdigest(),
        seed=seed, cases=rows)


def outputs():
    from lib.knowledge.html_text import _VOID, _HIDDEN, _ENTITIES
    lines = ['//! @generated by scripts/gen_native_html_projection.py; do not edit.',
             '//! Entity data originates in Python html.entities (PSF license).']
    lines.extend('pub const '+name+': &str = '+rust_string(value)+';' for name,value in [
        ('PYTHON_VERSION',sys.version.split()[0]),
        ('TOKENIZER_SHA256',hashlib.sha256(Path(html.parser.__file__).read_bytes()).hexdigest()),
        ('OWNER_SHA256',hashlib.sha256((ROOT/'lib/knowledge/html_text.py').read_bytes()).hexdigest())])
    for name, values in [('VOID', sorted(_VOID)), ('HIDDEN', sorted(_HIDDEN)),
            ('CDATA', html.parser.HTMLParser.CDATA_CONTENT_ELEMENTS),
            ('RCDATA', html.parser.HTMLParser.RCDATA_CONTENT_ELEMENTS)]:
        lines.append(f'pub const {name}: &[&str] = &['+','.join(rust_string(v) for v in values)+'];')
    whitespace = [ord(chr(i)) for i in range(sys.maxunicode+1) if chr(i).isspace()]
    lines.append('pub fn whitespace(value: char) -> bool { matches!(value as u32, '+
                 ' | '.join(str(i) for i in whitespace)+') }')
    lines.append(f'pub const DECIMAL_DIGITS: usize = {sys.get_int_max_str_digits()};')
    values = []
    for i in range(128,160):
        try: value = bytes([i]).decode('cp1252')
        except UnicodeDecodeError: value = chr(i)
        values.append("'\\u{"+format(ord(value),'x')+"}'")
    lines.append('pub const C1: [char;32] = ['+','.join(values)+'];')
    lower,flags = casing_tables()
    lines.append('pub const LOWER: &[(u32, &str)] = &[')
    lines.extend('('+str(i)+','+rust_string(value)+'),' for i,value in lower)
    lines.append('];')
    for name, values in flags.items():
        name = 'CASED' if name == 'Cased' else 'CASE_IGNORABLE'
        lines.append('pub const '+name+': &[(u32,u32)] = &['+
                     ','.join('('+str(a)+','+str(b)+')' for a,b in values)+'];')
    lines.append('pub const ENTITIES: &[(&str, &str)] = &[')
    lines.extend('('+rust_string(k)+','+rust_string(v)+'),' for k,v in sorted(_ENTITIES.items()))
    lines.append('];')
    data = oracle()
    return {ROOT/'packages/tofu-runtime/src/generated_html_projection.rs':'\n'.join(lines)+'\n',
        ROOT/'lib/knowledge/generated_native_html_profile.py':
            '"""Generated by gen_native_html_projection.py; do not edit."""\nPROFILE = '+
            repr({key:data[key] for key in ('python_version','tokenizer_sha256','owner_sha256')})+'\n',
        ROOT/'packages/tofu-runtime/tests/fixtures/python_html_projection.json':json.dumps(data,ensure_ascii=True,separators=(',',':'))+'\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output-oracle', type=Path)
    parser.add_argument('--seed', type=int, default=20261015)
    parser.add_argument('--count', type=int, default=2048)
    args = parser.parse_args()
    if args.output_oracle:
        args.output_oracle.write_text(json.dumps(oracle(args.seed,args.count),ensure_ascii=True)+'\n')
        return
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('native HTML projection drift: '+str(path))
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
