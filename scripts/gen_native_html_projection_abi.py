"""Generate native HTML ABI constants from its canonical lifetime contract."""
import argparse
import json
from pathlib import Path
import pprint
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def cffi_binding():
    import cffi
    from lib.agent_core.native_binary import MEMFD_CDEF
    builder = cffi.FFI()
    header = (ROOT / 'contracts/native_html_projection_abi_v1.h').read_text()
    declarations = '\n'.join(line for line in header.splitlines()
                             if not line.startswith('#'))
    builder.cdef(declarations + '\n' + MEMFD_CDEF)
    builder.set_source('lib.knowledge.generated_native_html_cffi', None)
    with tempfile.TemporaryDirectory() as temporary:
        generated = Path(builder.compile(tmpdir=temporary))
        return ('# Generated by scripts/gen_native_html_projection_abi.py; do not edit.\n'
                + generated.read_text())


def outputs():
    spec = json.loads((ROOT / 'contracts/native_html_projection_abi_v1.json').read_text())
    lines = ['//! @generated by scripts/gen_native_html_projection_abi.py; do not edit.',
             f"pub const ABI_VERSION: u32 = {spec['abi_version']};"]
    lines += [f'pub const STATUS_{key}: u32 = {value};' for key, value in spec['status'].items()]
    return {
        ROOT / 'packages/tofu-runtime/src/generated_html_projection_abi.rs': '\n'.join(lines) + '\n',
        ROOT / 'lib/agent_core/native_html_projection_contract.py':
            '"""Generated from native_html_projection_abi_v1.json; do not edit."""\n'
            + 'SPEC = ' + pprint.pformat(spec, sort_dicts=False, width=100) + '\n',
        ROOT / 'lib/knowledge/generated_native_html_cffi.py': cffi_binding(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'native HTML ABI differs: {path.name}; regenerate')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
