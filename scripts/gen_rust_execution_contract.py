#!/usr/bin/env python3
"""Derive native execution labels from the retained canonical Python owner.

This is development-time generation, not a native runtime dependency. Check mode
refuses drift; it parses literal labels, closed resources and usage aliases.
"""
import argparse
import ast
import json
import pprint
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/agent_core/execution_session.py'
REPLAY = ROOT / 'lib/task_replay.py'
TOOL_FLOOD = ROOT / 'lib/llm/tool_call_flood.py'
TOOL_CALLER = ROOT / 'lib/tool_caller_identity.py'
SSE_CORE = ROOT / 'lib/llm/_sse_core.py'
STREAM_RESULT = ROOT / 'lib/llm/stream_result.py'
SSE = ROOT / 'lib/llm/_sse_framer.py'
TARGET = ROOT / 'packages/tofu-runtime/src/execution_contract.rs'


def generate():
    tree = ast.parse(SOURCE.read_text())
    output = ['// Generated by scripts/gen_rust_execution_contract.py; do not edit.',
              '// Authority: lib/agent_core/execution_session.py.', '']
    for name in ['ExecutionPhase', 'ResourceDisposition']:
        node = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == name)
        values = [(n.targets[0].id, ast.literal_eval(n.value)) for n in node.body if isinstance(n, ast.Assign)]
        output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]', 'pub enum '+name+' {']
        output += ['    '+key.title().replace('_', '')+',' for key, _ in values]
        output += ['}', 'impl '+name+' {', "    pub fn as_str(self) -> &'static str {", '        match self {']
        output += ['            Self::'+key.title().replace('_', '')+' => "'+value+'",' for key, value in values]
        output += ['        }', '    }', '}', '']
    terminals = next(n for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == 'TERMINAL_EXECUTION_PHASES')
    terminal_names = sorted(node.attr.title().replace('_', '') for node in terminals.value.args[0].elts)
    order = next(n for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == '_PRE_TERMINAL_ORDER')
    ranks = [(key.attr.title().replace('_', ''), ast.literal_eval(value)) for key, value in zip(order.value.keys, order.value.values)]
    output += ['#[rustfmt::skip]', 'impl ExecutionPhase {', '    pub fn is_terminal(self) -> bool {',
               '        matches!(self, '+ ' | '.join('Self::'+name for name in terminal_names)+')', '    }',
               '    pub fn lifecycle_order(self) -> Option<u8> {', '        match self {']
    output += ['            Self::'+name+' => Some('+str(rank)+'),' for name, rank in ranks]
    output += ['            _ => None,', '        }', '    }', '}', '']
    declaration = next(n for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == '_ALLOWED_RESOURCE_NAMES')
    names = sorted(ast.literal_eval(declaration.value.args[0]))
    output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]', 'pub enum ResourceName {']
    output += ['    '+name.title().replace('_', '')+',' for name in names]
    output += ['}', 'impl ResourceName {', "    pub fn as_str(self) -> &'static str {", '        match self {']
    output += ['            Self::'+name.title().replace('_', '')+' => "'+name+'",' for name in names]
    output += ['        }', '    }', '}', '']
    replay = ast.parse(REPLAY.read_text())
    for target in ['TASK_REPLAY_EVENT_TYPE_FIELD', 'TASK_REPLAY_EVENT_SEQUENCE_FIELD', 'TASK_REPLAY_TERMINAL_STATUSES', 'TASK_REPLAY_TERMINAL_EVENT_TYPES']:
        declaration = next(n for n in replay.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id == target)
        value = ast.literal_eval(declaration.value)
        if isinstance(value, str):
            output += ['pub const '+target+': &str = "'+value+'";', '']
        else:
            output += ['pub const '+target+': &[&str] = &['+', '.join('"'+name+'"' for name in value)+'];', '']
    framing = ast.parse(SSE.read_text())
    diagnostics = next(n for n in framing.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id == '_MAX_PENDING_DIAGNOSTICS')
    output += ['pub const MAX_SSE_PENDING_DIAGNOSTICS: usize = '+str(ast.literal_eval(diagnostics.value))+';', '']
    result_tree = ast.parse(STREAM_RESULT.read_text())
    states = next(n for n in result_tree.body if isinstance(n, ast.ClassDef) and n.name == 'ProviderStreamState')
    values = [(n.targets[0].id, ast.literal_eval(n.value)) for n in states.body if isinstance(n, ast.Assign)]
    variant = lambda key: key.title().replace('_', '')
    output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum ProviderStreamState {']
    output += ['    '+variant(key)+',' for key, _ in values]
    output += ['}', 'impl ProviderStreamState {', "    pub fn as_str(self) -> &'static str {", '        match self {']
    output += ['            Self::'+variant(key)+' => "'+value+'",' for key,value in values]
    output += ['        }', '    }', '}', '']
    classify = next(n for n in result_tree.body if isinstance(n, ast.FunctionDef) and n.name == 'classify_provider_stream_state')
    args = [n.arg for n in classify.args.kwonlyargs]
    output += ['#[derive(Default)]', 'pub struct StreamFacts {']
    output += ['    pub '+name+': '+('u64' if name == 'malformed_frame_count' else 'bool')+',' for name in args]
    output += ['}', '#[rustfmt::skip]', 'pub fn classify_stream(facts: &StreamFacts) -> ProviderStreamState {']
    def expression(n):
        if isinstance(n, ast.Name): return 'facts.'+n.id
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.Not): return '!'+expression(n.operand)
        if isinstance(n, ast.BoolOp) and isinstance(n.op, ast.Or): return ' || '.join(expression(v) for v in n.values)
        if isinstance(n, ast.Compare) and len(n.ops)==1 and isinstance(n.ops[0], ast.Gt): return expression(n.left)+' > '+str(ast.literal_eval(n.comparators[0]))
        raise ValueError('unsupported stream classifier expression: '+ast.dump(n))
    for statement in classify.body:
        if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant): continue
        if isinstance(statement, ast.If):
            assert len(statement.body)==1 and not statement.orelse and isinstance(statement.body[0],ast.Return)
            output += ['    if '+expression(statement.test)+' { return ProviderStreamState::'+variant(statement.body[0].value.attr)+'; }']
        elif isinstance(statement, ast.Return): output += ['    ProviderStreamState::'+variant(statement.value.attr)]
        else: raise ValueError('unsupported stream classifier statement')
    output += ['}', '']
    for target in ['_GATEWAY_LIMIT_MAX_CHARS', '_GATEWAY_LIMIT_PHRASES']:
        declaration = next(n for n in result_tree.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id==target)
        value = ast.literal_eval(declaration.value)
        output += ['#[rustfmt::skip]', 'pub const '+target.lstrip('_')+(': usize = '+str(value)+';' if isinstance(value,int) else ': &[&str] = &['+', '.join('"'+v+'"' for v in value)+'];'), '']
    core = ast.parse(SSE_CORE.read_text())
    for target in ['_MAX_CONSECUTIVE_PARSE_ERRORS', '_MAX_TOOL_CALL_INDEX', '_MAX_TOOL_CALL_ID_CHARS']:
        declaration = next(n for n in core.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id==target)
        output += ['pub const '+target.lstrip('_')+': usize = '+str(ast.literal_eval(declaration.value))+';', '']
    caller_tree = ast.parse(TOOL_CALLER.read_text())
    caller_limit = next(n for n in caller_tree.body if isinstance(n, ast.Assign) and n.targets[0].id == 'MAX_TOOL_CALLER_ID_CHARS')
    output += ['pub const MAX_TOOL_CALLER_ID_CHARS: usize = '+str(ast.literal_eval(caller_limit.value))+';', '']
    flood_tree = ast.parse(TOOL_FLOOD.read_text())
    resolve = next(n for n in flood_tree.body if isinstance(n, ast.FunctionDef) and n.name == 'identical_tool_call_limit')
    outer = next(n for n in ast.walk(resolve) if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id=='max')
    inner = outer.args[1]
    assert isinstance(inner, ast.Call) and inner.func.id=='min'
    env_default = next(n for n in ast.walk(resolve) if isinstance(n,ast.Call) and isinstance(n.func,ast.Attribute) and n.func.attr=='get')
    for name,value in [('MIN_IDENTICAL_TOOL_CALLS',ast.literal_eval(outer.args[0])),('MAX_IDENTICAL_TOOL_CALLS',ast.literal_eval(inner.args[0])),('DEFAULT_IDENTICAL_TOOL_CALLS',int(ast.literal_eval(env_default.args[1])))]:
        output += ['pub const '+name+': usize = '+str(value)+';', '']
    def flood_branch(tree):
        return next(n for n in ast.walk(tree) if isinstance(n, ast.If) and isinstance(n.test,ast.Call) and isinstance(n.test.func,ast.Name) and n.test.func.id=='isinstance' and isinstance(n.test.args[1],ast.Name) and n.test.args[1].id=='ProviderToolCallFloodError')
    build_tree = ast.parse((ROOT/'lib/error_envelope/_build.py').read_text())
    branch = flood_branch(build_tree)
    assigned = {n.targets[0].id:n.value for n in branch.body if isinstance(n,ast.Assign)}
    classify_tree = ast.parse((ROOT/'lib/error_envelope/_classify.py').read_text())
    kind = ast.literal_eval(flood_branch(classify_tree).body[0].value)
    constants_tree = ast.parse((ROOT/'lib/error_envelope/_constants.py').read_text())
    def kinds(name):
        n = next(n for n in constants_tree.body if isinstance(n,ast.Assign) and n.targets[0].id==name)
        return ast.literal_eval(n.value.args[0] if isinstance(n.value,ast.Call) else n.value)
    errors_tree = ast.parse((ROOT/'lib/llm_errors.py').read_text())
    error_class = next(n for n in errors_tree.body if isinstance(n,ast.ClassDef) and n.name=='ProviderToolCallFloodError')
    stage = ast.literal_eval(next(n.value for n in error_class.body if isinstance(n,ast.Assign) and n.targets[0].id=='failure_stage'))
    envelope = dict(kind=kind,severity='warning' if kind in kinds('_WARNING_KINDS') else 'error',retryable=kind in kinds('_RETRYABLE_KINDS'),message=ast.literal_eval(assigned['message']),hint=ast.literal_eval(assigned['hint']),detail='',model='',context='',source='llm',raw='',failureStage=stage)
    extensions = assigned['extensions']
    for key,value in zip(extensions.keys,extensions.values):
        if isinstance(value,ast.Constant): envelope[ast.literal_eval(key)] = ast.literal_eval(value)
    output += ['#[rustfmt::skip]', 'pub const TOOL_FLOOD_ENVELOPE_JSON: &str = r#"'+json.dumps(envelope,ensure_ascii=False,separators=(',',':'))+'"#;', '']
    prefixes = next(n for n in core.body if isinstance(n,ast.Assign) and n.targets[0].id=='_INTERNAL_TOOL_PREFIXES')
    output += ['pub const INTERNAL_TOOL_PREFIXES: &[&str] = &['+', '.join(json.dumps(v) for v in ast.literal_eval(prefixes.value))+'];', '']
    contract_tree = ast.parse((ROOT/'lib/tools/contracts.py').read_text())
    error_class = next(n for n in contract_tree.body if isinstance(n,ast.ClassDef) and n.name=='ToolContractError')
    init = next(n for n in error_class.body if isinstance(n,ast.FunctionDef) and n.name=='__init__')
    default_action = next(value for arg,value in zip(init.args.kwonlyargs,init.args.kw_defaults) if arg.arg=='next_action')
    output += ['pub const TOOL_CONTRACT_NEXT_ACTION: &str = '+json.dumps(ast.literal_eval(default_action))+';', '']
    contract_class = next(n for n in contract_tree.body if isinstance(n,ast.ClassDef) and n.name=='ToolContractV2')
    version = next(n.value for n in contract_class.body if isinstance(n,ast.AnnAssign) and n.target.id=='contract_version')
    version = next(k.value for k in version.keywords if k.arg=='default')
    output += ['pub const TOOL_CONTRACT_VERSION: &str = '+json.dumps(ast.literal_eval(version))+';', '']
    codes = sorted({ast.literal_eval(n.args[0]) for n in ast.walk(contract_tree) if isinstance(n,ast.Call) and isinstance(n.func,ast.Name) and n.func.id=='ToolContractError'})
    output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum ToolContractCode {']
    output += ['    '+name.title().replace('_','')+',' for name in codes]
    output += ['}', 'impl ToolContractCode {', "    pub fn as_str(self) -> &'static str {", '        match self {']
    output += ['            Self::'+name.title().replace('_','')+' => '+json.dumps(name)+',' for name in codes]
    output += ['        }', '    }', '}', '']
    permission = next(n.value for n in contract_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='ToolPermission')
    permissions = [ast.literal_eval(n) for n in permission.slice.elts]
    output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum ToolPermission {']
    output += ['    '+value.title()+',' for value in permissions]
    output += ['}', '']
    budget = next(n for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == '_MAX_RESOURCES_PER_EXECUTION')
    output += ['pub const MAX_RESOURCES_PER_EXECUTION: usize = '+str(ast.literal_eval(budget.value))+';', '']
    responses_tree = ast.parse((ROOT / 'lib/llm/responses_outbound/_sse.py').read_text())
    for source_name,target_name in [('_MAX_RESPONSE_OUTPUT_INDEX','RESPONSES_MAX_OUTPUT_INDEX'),('_MAX_RESPONSE_ITEM_ID_CHARS','RESPONSES_MAX_ITEM_ID_CHARS'),('_MAX_RESPONSE_TOOL_NAME_CHARS','RESPONSES_MAX_TOOL_NAME_CHARS')]:
        value = next(n.value for n in responses_tree.body if isinstance(n,ast.Assign) and n.targets[0].id==source_name)
        output += ['pub const '+target_name+': usize = '+str(ast.literal_eval(value))+';', '']
    alias_tree = ast.parse((ROOT / 'lib/llm/conversion.py').read_text())
    alias_fn = next(n for n in alias_tree.body if isinstance(n,ast.FunctionDef) and n.name=='tool_name_reverse')
    limits = {n.comparators[0].value for n in ast.walk(alias_fn) if isinstance(n,ast.Compare) and isinstance(n.left,ast.Call) and isinstance(n.left.func,ast.Name) and n.left.func.id=='len' and isinstance(n.comparators[0],ast.Constant)}
    assert limits == {64}, 'Canonical alias limit changed'
    slices = [n for n in ast.walk(alias_fn) if isinstance(n,ast.Subscript) and isinstance(n.slice,ast.Slice) and isinstance(n.slice.upper,ast.Constant)]
    prefix = next(n.slice.upper.value for n in slices if isinstance(n.value,ast.Name) and n.value.id=='name')
    digest = next(n.slice.upper.value for n in slices if isinstance(n.value,ast.Call))
    for name,value in [('RESPONSES_ALIAS_MAX_CHARS',next(iter(limits))),('RESPONSES_ALIAS_PREFIX_CHARS',prefix),('RESPONSES_ALIAS_DIGEST_CHARS',digest)]:
        output += ['pub const '+name+': usize = '+str(value)+';', '']
    response_body_tree = ast.parse((ROOT / 'lib/llm/responses_outbound/_to_responses.py').read_text())
    profiles = ast.literal_eval(next(n.value for n in response_body_tree.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name) and n.target.id == 'RESPONSES_PROFILES'))
    codex = profiles['codex']
    output += ['pub const RESPONSES_CODEX_INSTRUCTIONS: &str = '+json.dumps(codex['instructions'])+';',
               'pub const RESPONSES_CODEX_SUMMARY: &str = '+json.dumps(codex['reasoning_summary'])+';',
               'pub const RESPONSES_CODEX_DROP_PARAMS: &[&str] = &['+', '.join(json.dumps(v) for v in codex['drop_params'])+'];',
               'pub const RESPONSES_CODEX_INCLUDE: &[&str] = &['+', '.join(json.dumps(v) for v in codex['include'])+'];', '']

    replay = next(n.value for n in response_body_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='_REPLAY_RESPONSE_ITEM_TYPES')
    types = sorted(ast.literal_eval(replay.args[0]) | {'compaction'})
    output += ['pub const RESPONSES_REPLAY_ITEM_TYPES: &[&str] = &['+', '.join(json.dumps(t) for t in types)+'];', '']
    phase_tree = ast.parse((ROOT / 'lib/llm/responses_outbound/_message_phase.py').read_text())
    phases = next(n.value for n in phase_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='_PHASES')
    output += ['pub const RESPONSES_MESSAGE_PHASES: &[&str] = &['+', '.join(json.dumps(p) for p in sorted(ast.literal_eval(phases.args[0])))+'];', '']
    for source_name,target_name in [('MAX_PHASE_MESSAGES','RESPONSES_MAX_PHASE_MESSAGES'),('MAX_PHASE_TEXT_BYTES','RESPONSES_MAX_PHASE_TEXT_BYTES')]:
        value = next(n.value for n in phase_tree.body if isinstance(n,ast.Assign) and n.targets[0].id==source_name)
        number = (ast.literal_eval(value.left)*ast.literal_eval(value.right) if isinstance(value,ast.BinOp) and isinstance(value.op,ast.Mult) else ast.literal_eval(value))
        output += ['pub const '+target_name+': usize = '+str(number)+';', '']
    frame_defs = json.loads((ROOT / 'contracts/native_agent_stdio_v1.schema.json').read_text())['$defs']
    for name, keys in [('NATIVE_TEXT_BLOCK_KEYS',frame_defs['tool_model_text']['properties']),('NATIVE_IMAGE_BLOCK_KEYS',frame_defs['tool_model_image']['properties']),('NATIVE_IMAGE_SOURCE_KEYS',frame_defs['tool_model_image']['properties']['image_url']['properties'])]:
        output += ['pub const '+name+': &[&str] = &['+', '.join(json.dumps(k) for k in keys)+'];', '']
    minimum = frame_defs['tool_model_image']['properties']['image_url']['properties']['url']['minLength']
    output += ['pub const NATIVE_IMAGE_URL_MIN_CHARS: usize = '+str(minimum)+';', '']
    details = frame_defs['tool_model_image']['properties']['image_url']['properties']['detail']['enum']
    output += ['pub const NATIVE_IMAGE_DETAILS: &[&str] = &['+', '.join(json.dumps(k) for k in details)+'];', '']
    image_tree = ast.parse((ROOT / 'lib/image_mime.py').read_text())
    magics = ast.literal_eval(next(n.value for n in image_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='IMAGE_MIME_MAGICS'))
    output += ['pub const IMAGE_MIME_MAGICS: &[(&[u8], &str)] = &[']
    output += ['    (&['+', '.join(str(b) for b in magic)+'], '+json.dumps(mime)+'),' for magic,mime in magics.items()]
    output += ['];', '']
    anthropic_tree = ast.parse((ROOT / 'lib/llm/anthropic_outbound/_sse.py').read_text())
    for source_name, target_name in [('_MAX_CONTENT_BLOCK_INDEX','ANTHROPIC_MAX_BLOCK_INDEX'),('_MAX_TOOL_USE_ID_CHARS','ANTHROPIC_MAX_TOOL_ID_CHARS'),('_MAX_TOOL_NAME_CHARS','ANTHROPIC_MAX_TOOL_NAME_CHARS')]:
        value = next(n.value for n in anthropic_tree.body if isinstance(n,ast.Assign) and n.targets[0].id==source_name)
        output += ['pub const '+target_name+': usize = '+str(ast.literal_eval(value))+';', '']
    inbound_tree = ast.parse((ROOT / 'lib/llm/anthropic_outbound/_from_anthropic.py').read_text())
    stop_map = ast.literal_eval(next(n.value for n in inbound_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='_STOP_REASON_MAP'))
    output += ['pub fn anthropic_stop_reason(reason: &str) -> &str {', '    match reason {']
    output += ['        '+json.dumps(key)+' => '+json.dumps(value)+',' for key,value in stop_map.items()]
    output += ['        other => other,', '    }', '}', '']
    approval_tree = ast.parse((ROOT / 'lib/tasks_pkg/tool_dispatch/_approval.py').read_text())
    for source_name, target_name in [('_TOOL_APPROVAL_RECEIPT_MAX','DEFAULT_APPROVAL_RECEIPTS'),('_TOOL_APPROVAL_RECEIPT_TTL_SECONDS','APPROVAL_RECEIPT_TTL_SECONDS')]:
        declaration = next(n for n in approval_tree.body if isinstance(n,ast.Assign) and n.targets[0].id==source_name)
        output += ['pub const '+target_name+': usize = '+str(ast.literal_eval(declaration.value))+';', '']
    authorities = ast.literal_eval(next(n.value for n in approval_tree.body if isinstance(n,ast.Assign) and n.targets[0].id=='_TOOL_APPROVAL_RECEIPT_AUTHORITIES'))
    output += ['#[derive(Clone, Copy, Debug, PartialEq, Eq)]','pub enum ApprovalAuthority {']
    output += ['    '+name.title().replace('_','')+',' for name in authorities]
    output += ['}', 'impl ApprovalAuthority {', "    pub fn as_str(self) -> &'static str {", '        match self {']
    output += ['            Self::'+name.title().replace('_','')+' => '+json.dumps(name)+',' for name in authorities]
    output += ['        }','    }','}', '']
    cost_tree = ast.parse((ROOT / 'lib/cost.py').read_text())
    for source_name in ('_USAGE_KEY_ALIASES', '_USAGE_NESTED_ALIASES'):
        declaration = next(n for n in cost_tree.body if isinstance(n, ast.Assign) and n.targets[0].id == source_name)
        values = ast.literal_eval(declaration.value)
        for canon, aliases in values.items():
            name = 'USAGE_' + canon.upper() + ('_NESTED' if 'NESTED' in source_name else '_KEYS')
            if 'NESTED' in source_name:
                rows = ', '.join('(' + json.dumps(parent) + ', ' + json.dumps(key) + ')' for parent, key in aliases)
                output += ['pub const ' + name + ': &[(&str, &str)] = &[' + rows + '];', '']
            else:
                output += ['pub const ' + name + ': &[&str] = &[' + ', '.join(json.dumps(key) for key in aliases) + '];', '']
    token_base = ast.parse((ROOT / 'lib/token_counter/base.py').read_text())
    for source_name, target_name in [('_IMAGE_TOKENS_DEFAULT', 'TOKEN_IMAGE_OVERHEAD'), ('_STRUCTURAL_OVERHEAD_TOKENS', 'TOKEN_REQUEST_OVERHEAD')]:
        value = next(n.value for n in token_base.body if isinstance(n, ast.Assign) and n.targets[0].id == source_name)
        output += ['pub const ' + target_name + ': u64 = ' + str(ast.literal_eval(value)) + ';', '']
    token_counter = ast.parse((ROOT / 'lib/token_counter/tiktoken_counter.py').read_text())
    counter = next(n for n in token_counter.body if isinstance(n, ast.ClassDef) and n.name == 'TiktokenCounter')
    count = next(n for n in counter.body if isinstance(n, ast.FunctionDef) and n.name == 'count')
    overhead = next(n.value for n in ast.walk(count) if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'per_msg_overhead')
    output += ['pub const TOKEN_MESSAGE_OVERHEAD: u64 = ' + str(ast.literal_eval(overhead)) + ';', '']
    tool_projection = json.loads((ROOT / 'contracts/native_agent_stdio_v1.schema.json').read_text())['model_tool_projection']
    assert tool_projection['order']=='catalog' and tool_projection['catalog_name_field']=='name'
    projection = json.dumps(tool_projection,separators=(',',':'))
    output += ['#[rustfmt::skip]', 'pub const NATIVE_MODEL_TOOL_PROJECTION_JSON: &str = r#"'+projection+'"#;', '']
    output += ['pub fn native_model_tools(tools: &serde_json::Map<String,serde_json::Value>) -> Vec<serde_json::Value> {',
        '    tools.iter().map(|(name,tool)|serde_json::json!({"type":'+json.dumps(tool_projection['type'])+',"function":{"name":name,"description":tool['+json.dumps(tool_projection['description_field'])+'].as_str().unwrap_or('+json.dumps(tool_projection['missing_description'])+'),"parameters":tool['+json.dumps(tool_projection['parameters_field'])+']}})).collect()', '}', '']
    header_policy = json.loads((ROOT / 'contracts/native_agent_stdio_v1.schema.json').read_text())['model_dispatch_header_policy']
    output += ['pub const MODEL_DISPATCH_FORBIDDEN_HEADERS: &[&str] = &['+', '.join(json.dumps(name) for name in header_policy['forbidden'])+'];', '']
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    expected = generate()
