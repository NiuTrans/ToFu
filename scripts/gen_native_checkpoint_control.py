#!/usr/bin/env python3
"""Generate standalone checkpoint C ABI constants from its canonical contract."""
from pathlib import Path as Path
import argparse as argparse
import json as json
ROOT=Path(__file__).resolve().parents[1]
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 spec=json.loads((ROOT/'contracts/native_checkpoint_control_v1.schema.json').read_text())
 ir=json.loads((ROOT/'contracts/tofudb_ir_v1.json').read_text())
 operations=tuple(key for key in spec['$defs'] if key not in {'binding','response','frontier_observation'})
 output='"""Generated by scripts/gen_native_checkpoint_control.py; do not edit."""\n\n'+f'FORMAT = {spec["$id"]!r}\nRESPONSE_HEADROOM_BYTES = {spec["limits"]["responseHeadroomBytes"]!r}\nINVOICE_HEADER_BYTES = {spec["limits"]["invoiceHeaderBytes"]!r}\nOPERATIONS = {operations!r}\n'
 output+=f'GOAL_HANDOFF_ROW_HEADROOM_BYTES = {spec["limits"]["goalHandoffRowHeadroomBytes"]!r}\n'
 output+=f'CHECKPOINT_DOCUMENT_MAX_BYTES = {ir["bounds"]["maximumLegacyDocumentBytes"]!r}\n'
 claim=json.loads((ROOT/'contracts/native_goal_actor_claim_v1.schema.json').read_text())
 output+=f'GOAL_CLAIM_FORMAT = {claim["$id"]!r}\n'
 cost=json.loads((ROOT/'contracts/native_aggregate_cost_v1.schema.json').read_text())
 output+=f'AGGREGATE_COST_SCHEMA = {cost!r}\n'
 handoff=json.loads((ROOT/'contracts/native_goal_actor_handoff_v1.schema.json').read_text())
 def inline(value):
  if isinstance(value,list):return [inline(item) for item in value]
  if not isinstance(value,dict):return value
  if '$ref' in value:
   target=handoff
   for key in value['$ref'].removeprefix('#/').split('/'):target=target[key]
   return inline(target)
  return {key:inline(item) for key,item in value.items()}
 output+=f'GOAL_CONSUMPTION_RECEIPT_SCHEMA = {inline(handoff["$defs"]["consumption_receipt"])!r}\n'
 output+=f'FRONTIER_OBSERVATION_SCHEMA = {spec["$defs"]["frontier_observation"]!r}\n'
 transport=spec['daemonTransport']
 output+=f'TRANSPORT_FORMAT = {transport["format"]!r}\nCAPABILITIES_OPERATION = {transport["capabilitiesOperation"]!r}\nCONTROL_OPERATION = {transport["controlOperation"]!r}\n'
 target=ROOT/'tofu_db/generated_checkpoint_control.py'
 if args.check:
  if not target.exists() or target.read_text()!=output:raise SystemExit('checkpoint control constants differ; regenerate')
 else:target.write_text(output)
 rust='// Generated by scripts/gen_native_checkpoint_control.py; do not edit.\n'+''.join(f'pub(crate) const {name}: &str = {json.dumps(transport[key])};\n' for name,key in [('FORMAT','format'),('CAPABILITIES','capabilitiesOperation'),('CONTROL','controlOperation')])
 for target,content in [(ROOT/'packages/tofu-db/src/generated_checkpoint_transport.rs',rust),(ROOT/'packages/tofu-db/contracts/native_checkpoint_control_v1.schema.json',(ROOT/'contracts/native_checkpoint_control_v1.schema.json').read_text())]:
  if args.check:
   if not target.exists() or target.read_text()!=content:raise SystemExit(f'checkpoint generated contract differs: {target}; regenerate')
  else:target.write_text(content)
if __name__=='__main__':main()
