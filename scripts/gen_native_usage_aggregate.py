"""Generate additive-usage labels/oracle from the canonical Python accumulator."""
import argparse
import ast
import json
from pathlib import Path
import random
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    from lib.cost import accumulate_usage_into
    tree=ast.parse((ROOT/'lib/cost.py').read_text())
    assignment=next(node for node in tree.body if isinstance(node,ast.Assign)
        and any(isinstance(target,ast.Name) and target.id=='_ADDITIVE_USAGE_DETAILS' for target in node.targets))
    details=sorted(ast.literal_eval(assignment.value.args[0]))
    summary=json.loads((ROOT/'contracts/native_agent_stdio_v1.schema.json').read_text())['$defs']['additive_usage_summary']
    if set(summary['properties']['counts']['properties'])!=set(details):
        raise SystemExit('native additive detail schema drift')
    rounds=[[],[None,True,[],{'prompt_tokens':3},{'prompt_tokens':2.5,'output_tokens':1}],
        [{'x':1,'_private':9,'flag':True,'negative':-1,'text':'3'}, {'x':2}],
        [{'prompt_tokens_details':{'cached_tokens':2,'_private':7,'flag':False}},
         {'prompt_tokens_details':{'cached_tokens':3,'ignored':{'n':1}},'completion_tokens_details':{'reasoning_tokens':1}}],
        [{'x':1e308},{'x':1e308}], [{'x':-0.0},{'x':0.5}],
        [{'x':18446744073709551615}],
        [{'cache_creation':4},{'cache_creation':{'ignored':False}}],
        [{'cache_creation':{'tokens':3}},{'cache_creation':2},{'cache_creation':{'tokens':1}}]]
    randomizer=random.Random(8123)
    for _ in range(100):
        rows=[]
        for _ in range(randomizer.randrange(1,8)):
            row={key:randomizer.choice([None,True,False,-1,0,1,2.5,19,'4',[2]])
                 for key in ('prompt_tokens','input_tokens','output_tokens','public','_private')}
            for detail in details:
                row[detail]={'cached_tokens':randomizer.randrange(100),'ignored':False}
            rows.append(row)
        rounds.append(rows)
    cases=[]
    for rows in rounds:
        total={}
        for row in rows:accumulate_usage_into(total,row)
        cases.append({'rounds':rows,'expected':total})
    labels='//! @generated by scripts/gen_native_usage_aggregate.py; do not edit.\n'
    labels+='pub const ADDITIVE_DETAILS: &[&str] = &['+','.join(json.dumps(name) for name in details)+'];\n'
    fixture={'format':'tofu.python-additive-usage-oracle/v1','native_integer_domain':'u64 with checked sums; wider evidence refuses before binding','cases':cases}
    fixture_text=json.dumps({key:value for key,value in fixture.items() if key!='cases'},sort_keys=True,indent=2).rstrip()[:-1].rstrip()+',\n  \"cases\": [\n'
    fixture_text+=',\n'.join('    '+json.dumps(case,sort_keys=True,separators=(',',':'),allow_nan=False) for case in cases)+'\n  ]\n}\n'
    outputs={ROOT/'packages/tofu-runtime/src/generated_usage_aggregate.rs':labels,
             ROOT/'packages/tofu-runtime/tests/fixtures/python_usage_aggregate.json':fixture_text}
    for path,text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('usage aggregate drift: '+path.name)
        else:path.write_text(text)


if __name__=='__main__':main()
