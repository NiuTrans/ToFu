"""Generate browser automation types from the definition and action authorities.

Entry point: python3 scripts/gen_automation_contract.py [--check]. This generator
does not evaluate schema references or contact providers; local definitions
become recursive TypeScript aliases and action I/O maps.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'frontend/src/api/automation.generated.ts'


def type_name(name: str) -> str:
    return 'Automation' + name[:1].upper() + name[1:]


def ts_type(schema: dict) -> str:
    if not schema:
        return 'AutomationJsonValue'
    if '$ref' in schema:
        ref = schema['$ref']
        if not ref.startswith('#/$defs/'):
            raise ValueError(f'Unsupported nonlocal automation reference: {ref}')
        return type_name(ref.rsplit('/', 1)[1])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    variants = schema.get('oneOf') or schema.get('anyOf')
    if variants:
        return ' | '.join(f'({ts_type(item)})' for item in variants)
    kind = schema.get('type')
    if kind == 'array':
        return f'ReadonlyArray<{ts_type(schema.get("items", {}))}>'
    if kind == 'object':
        properties = schema.get('properties', {})
        required = set(schema.get('required', []))
        members = [f'  readonly {json.dumps(name)}{"" if name in required else "?"}: {ts_type(child)};'
                   for name, child in properties.items()]
        if schema.get('additionalProperties', True) is not False:
            additional = schema.get('additionalProperties')
            value_type = ts_type(additional) if isinstance(additional, dict) else 'AutomationJsonValue'
            members.append(f'  readonly [key: string]: {value_type};')
        return '{\n' + '\n'.join(members) + '\n}'
    if kind in {'number', 'integer'}:
        return 'number'
    if kind in {'boolean', 'string', 'null'}:
        return kind
    raise ValueError(f'Unsupported automation schema: {schema}')


def generate() -> str:
    schema = json.loads((ROOT / 'contracts/automation_v1.schema.json').read_text())
    actions = json.loads((ROOT / 'contracts/automation_actions_v1.json').read_text())['actions']
    result = '// Generated by scripts/gen_automation_contract.py; do not edit.\n'
    result += ('export type AutomationJsonValue = null | boolean | number | string\n'
               '  | ReadonlyArray<AutomationJsonValue> | { readonly [key: string]: AutomationJsonValue };\n\n')
    for name, rule in schema['$defs'].items():
        result += f'export type {type_name(name)} = {ts_type(rule)};\n\n'
    result += f'export type AutomationDefinition = {ts_type(schema)};\n\n'
    result += 'export const AUTOMATION_LIMITS = ' + json.dumps(schema['x-limits']) + ' as const;\n'
    for key, name in [('runStates', 'RUN'), ('stepStates', 'STEP')]:
        result += f'export const AUTOMATION_{name}_STATES = {json.dumps(schema["x-runtime"][key])} as const;\n'
        result += f'export type Automation{name.title()}Status = typeof AUTOMATION_{name}_STATES[number];\n'
    result += '\nexport interface AutomationActionInputs {\n'
    for action in actions:
        result += f'  readonly {json.dumps(action["id"])}: {ts_type(action["input"])};\n'
    result += '}\n\nexport interface AutomationActionOutputs {\n'
    for action in actions:
        result += f'  readonly {json.dumps(action["id"])}: {ts_type(action["output"])};\n'
    result += '}\nexport type AutomationActionId = keyof AutomationActionInputs;\n'
    management = json.loads((ROOT / 'contracts/automation_management_v1.schema.json').read_text())

    def management_refs(value):
        if isinstance(value, dict):
            if value.get('$ref') == 'tofu.automation-action-output/task.show_time':
                return next(action['output'] for action in actions if action['id'] == 'task.show_time')
            if value.get('$ref') == 'tofu.automation/v1':
                return {'$ref': '#/$defs/definition'}
            return {key: ('#/$defs/Management' + child[len('#/$defs/'):]
                          if key == '$ref' and child.startswith('#/$defs/') else management_refs(child))
                    for key, child in value.items()}
        if isinstance(value, list):
            return [management_refs(child) for child in value]
        return value

    for name, rule in management['$defs'].items():
        result += f'\nexport type AutomationManagement{name} = {ts_type(management_refs(rule))};\n'
    result += '\nexport const AUTOMATION_MANAGEMENT_LIMITS = ' + json.dumps(management['x-limits']) + ' as const;\n'
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    content = generate()
    if arguments.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            raise SystemExit('Automation browser contract drift; regenerate with gen_automation_contract.py')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
