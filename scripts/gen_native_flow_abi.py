#!/usr/bin/env python3
"""Generate the native Flow ABI vocabulary from its machine-readable contract."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def outputs():
 spec=json.loads((ROOT/'contracts/native_flow_abi_v1.json').read_text())
 rust=['// Generated by scripts/gen_native_flow_abi.py; do not edit.',f"pub const ABI_VERSION: u32 = {spec['abi_version']};",f"pub const NONE: u64 = {spec['none_index']};"]
 for group in ('statuses','actions','queries'):
  prefix={'statuses':'STATUS','actions':'ACTION','queries':'QUERY'}[group]
  rust.extend(f"pub const {prefix}_{name.upper()}: u32 = {value};" for name,value in spec[group].items())
 for name,value in spec.get('verdict_flags',{}).items():
  rust.append(f'pub const VERDICT_{name.upper()}: u32 = {value};')
 rust.append('pub const VERDICT_FLAGS_MASK: u32 = '+str(sum(spec.get('verdict_flags',{}).values()))+';')
 for group in ('loop_config_fields','loop_body_fields','parallel_merge_fields'):
  rust.append('pub const '+group.upper()+': &[&str] = &['+','.join(json.dumps(v) for v in spec.get(group,[]))+'];')
 rust.extend(['#[repr(C)]','#[derive(Clone, Copy, Debug, PartialEq, Eq)]','pub struct Step {'])
 rust.extend(f'    pub {name}: {kind},' for name,kind in spec['step_fields'])
 rust.append('}')
 rust.extend(['#[repr(C)]','#[derive(Clone, Copy)]','pub struct Span {'])
 rust.extend(f'    pub {name}: '+{'bytes':'*const u8','usize':'usize'}[kind]+',' for name,kind in spec['span_fields'])
 rust.append('}')
 return {ROOT/'packages/tofu-runtime/src/generated_flow_abi.rs':'\n'.join(rust)+'\n',ROOT/'lib/orchestration/native_flow_contract.py':'"""Generated by scripts/gen_native_flow_abi.py; do not edit."""\nSPEC = '+repr(spec)+'\n'}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 for path,text in outputs().items():
  if args.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit('native Flow ABI generation drift: '+str(path))
  else:path.write_text(text)
if __name__=='__main__':main()
