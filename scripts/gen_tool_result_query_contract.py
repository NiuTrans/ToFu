#!/usr/bin/env python3
"""Generate package-owned result constants from the repository JSON contract."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/tool_result_query_v1.json'
OUTPUT = ROOT / 'lib/tool_results/tool_result_query_generated.py'


def render():
    contract = json.loads(SOURCE.read_text(encoding='utf-8'))
    return ('"""Generated by scripts/gen_tool_result_query_contract.py; do not edit.\n'
            'Data-only contract shared by application, storage and transient execution.\n"""\n'
            + 'CONTRACT = ' + pformat(contract, width=96, sort_dicts=False) + '\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != expected:
            print('Tool result query contract is stale; run ' + Path(__file__).name)
            return 1
        print('OK: tool result query contract is current')
    else:
        OUTPUT.write_text(expected, encoding='utf-8')
        print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
