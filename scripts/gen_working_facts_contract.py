"""Generate working-fact DTOs from their schema; --check detects drift."""
import argparse
import json
from pathlib import Path
from json_schema_types import ts_type

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/working_facts_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/working-facts.generated.ts'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    content = '// Generated by scripts/gen_working_facts_contract.py; do not edit.\n'
    for name, rule in schema['$defs'].items():
        content += f'export type {name} = {ts_type(rule)};\n\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Working facts contract drift')
    else:
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
