#!/usr/bin/env python3
"""Generate Python/Rust progress-batch bounds from task_event_delivery_v1.json."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_outputs(root: Path = ROOT) -> dict[Path, str]:
    policy = json.loads((root / 'contracts/task_event_delivery_v1.json').read_text())['progressBatch']
    frames, wire = policy['maxFrames'], policy['maxWireBytes']
    if any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in (frames, wire)):
        raise ValueError('Progress batch bounds must be positive integers')
    banner = 'Generated by scripts/gen_task_event_delivery_contract.py; do not edit.'
    return {
        root / 'lib/storage/generated_task_event_delivery_contract.py':
            f'"""{banner}"""\nPROGRESS_BATCH_MAX_FRAMES = {frames}\nPROGRESS_BATCH_MAX_WIRE_BYTES = {wire}\n',
        root / 'packages/tofu-db/src/generated_task_event_delivery.rs':
            f'// {banner}\npub const PROGRESS_BATCH_MAX_FRAMES: usize = {frames};\npub const PROGRESS_BATCH_MAX_WIRE_BYTES: usize = {wire};\n',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in generated_outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                print(f'Delivery contract drift: {path.relative_to(ROOT)}')
                return 1
        else:
            path.write_text(expected)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
