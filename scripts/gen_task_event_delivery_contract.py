#!/usr/bin/env python3
"""Generate delivery bounds and diagnostic anchor policy from the shared contract."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _positive_bounds(policy: dict, *names: str) -> tuple[int, ...]:
    values = tuple(policy[name] for name in names)
    if any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in values):
        raise ValueError(f'Batch bounds {names} must be positive integers')
    return values


def generated_outputs(root: Path = ROOT) -> dict[Path, str]:
    contract = json.loads((root / 'contracts/task_event_delivery_v1.json').read_text())
    frames, wire = _positive_bounds(contract['progressBatch'], 'maxFrames', 'maxWireBytes')
    structural = contract['structuralBatch']
    events, structural_wire = _positive_bounds(structural, 'maxEvents', 'maxWireBytes')
    if structural['command'] != 'turn.event.record_batch' or events < frames or structural_wire < wire:
        raise ValueError('A structural batch must carry every progress batch it may contain')
    banner = 'Generated by scripts/gen_task_event_delivery_contract.py; do not edit.'
    return {
        root / 'lib/storage/generated_task_event_delivery_profile.py':
            f'"""{banner}"""\nfrom lib.agent_core.generated_task_event_delivery_profile import DELIVERY_PROFILE_POLICY as DELIVERY_PROFILE_POLICY\n',
        root / 'lib/storage/generated_task_event_delivery_contract.py':
            f'"""{banner}"""\nfrom lib.agent_core.generated_task_event_delivery_contract import (\n    PROGRESS_BATCH_MAX_FRAMES as PROGRESS_BATCH_MAX_FRAMES,\n    PROGRESS_BATCH_MAX_WIRE_BYTES as PROGRESS_BATCH_MAX_WIRE_BYTES,\n    STRUCTURAL_BATCH_COMMAND as STRUCTURAL_BATCH_COMMAND,\n    STRUCTURAL_BATCH_MAX_EVENTS as STRUCTURAL_BATCH_MAX_EVENTS,\n    STRUCTURAL_BATCH_MAX_WIRE_BYTES as STRUCTURAL_BATCH_MAX_WIRE_BYTES,\n    DELIVERY_PROFILE_ENV as DELIVERY_PROFILE_ENV,\n)\n',

        root / 'lib/agent_core/generated_task_event_delivery_profile.py':
            f'"""{banner}"""\nDELIVERY_PROFILE_POLICY = {contract["performanceProfile"]!r}\n',
        root / 'lib/agent_core/generated_task_event_delivery_contract.py':
            f'"""{banner}"""\nPROGRESS_BATCH_MAX_FRAMES = {frames}\nPROGRESS_BATCH_MAX_WIRE_BYTES = {wire}\n'
            f'STRUCTURAL_BATCH_COMMAND = {structural["command"]!r}\n'
            f'STRUCTURAL_BATCH_MAX_EVENTS = {events}\nSTRUCTURAL_BATCH_MAX_WIRE_BYTES = {structural_wire}\n'
            f'DELIVERY_PROFILE_ENV = {contract["performanceProfile"]["environment"]!r}\n',
        root / 'packages/tofu-db/src/generated_task_event_delivery.rs':
            f'// {banner}\npub const PROGRESS_BATCH_MAX_FRAMES: usize = {frames};\npub const PROGRESS_BATCH_MAX_WIRE_BYTES: usize = {wire};\n'
            f'pub const STRUCTURAL_BATCH_MAX_EVENTS: usize = {events};\npub const STRUCTURAL_BATCH_MAX_WIRE_BYTES: usize = {structural_wire};\n',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in generated_outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                print(f'Delivery contract drift: {path.relative_to(ROOT)}')
                return 1
        else:
            path.write_text(expected)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
