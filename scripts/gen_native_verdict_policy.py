#!/usr/bin/env python3
"""Derive native verifier patterns/Unicode semantics from the retained Python owner."""
import argparse
import ast
import json
import unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def assignments(path):
 tree=ast.parse(path.read_text())
 return {node.targets[0].id:node.value for node in tree.body if isinstance(node,ast.Assign)
    and len(node.targets)==1 and isinstance(node.targets[0],ast.Name)}

def ranges(predicate):
 result=[];start=None
 for code in range(0x110000):
  if predicate(chr(code)):
   if start is None:start=code
  elif start is not None:result.append((start,code-1));start=None
 if start is not None:result.append((start,0x10ffff))
 return result

def charclass(entries):
 return '['+''.join('\\x{'+format(a,'x')+'}'+('' if a==b else '-\\x{'+format(b,'x')+'}') for a,b in entries)+']'

def generate():
 if unicodedata.unidata_version != '15.0.0':
  raise SystemExit('native verifier generation requires Python Unicode 15.0.0 (project Python 3.12)')
 verdict=assignments(ROOT/'lib/agent_verdict/_verdict.py')
 handoff=assignments(ROOT/'lib/agent_verdict/_handoff.py')
 space=ranges(str.isspace);word=ranges(lambda char:char=='_' or char.isalnum())
 decimal=ranges(lambda char:unicodedata.category(char)=='Nd')
 sc=charclass(space);dc=charclass(decimal)
 def pattern(raw, outer_boundary=False):
  if outer_boundary:
   if not (raw.startswith(r'\b') and raw.endswith(r'\b') and raw.count(r'\b')==2):
    raise SystemExit('native verifier boundary rule changed; review matcher')
   raw=raw[2:-2]
  output=[];i=0
  while i<len(raw):
   ch=raw[i]
   if ch=='\\' and i+1<len(raw):
    following=raw[i+1];output.append({'s':sc,'d':dc}.get(following,'\\'+following));i+=2;continue
   output.append({'i':'[iIİı]','s':'[sSſ]','k':'[kKK]'}.get(ch.lower(),'['+ch.lower()+ch.upper()+']' if ch.isascii() and ch.isalpha() else ch));i+=1
  return ''.join(output)
 names=['_PLAN_DEFECT_RE','_UNRESOLVED_PHRASE_RE','_LOOSE_STOP_RE','_LOOSE_CONTINUE_RE','_VERDICT_RE','_PROGRESS_RE']
 output=['// Generated by scripts/gen_native_verdict_policy.py; do not edit.',
    '// Authority: lib/agent_verdict/{_verdict,_handoff}.py and Python Unicode '+unicodedata.unidata_version+'.']
 for name in names:
  node=verdict.get(name) or handoff[name]
  raw=ast.literal_eval(node.args[0]);output.append(f'pub const {name.strip("_")}: &str = '+json.dumps(pattern(raw, name in ('_UNRESOLVED_PHRASE_RE','_LOOSE_STOP_RE','_LOOSE_CONTINUE_RE')),ensure_ascii=False)+';')
 tree=ast.parse((ROOT/'lib/agent_verdict/_verdict.py').read_text())
 clean=next(node for node in tree.body if isinstance(node,ast.FunctionDef) and node.name=='_clean_feedback')
 header=next(node for node in ast.walk(clean) if isinstance(node,ast.Call)
    and isinstance(node.func,ast.Attribute) and node.func.attr=='sub'
    and isinstance(node.func.value,ast.Name) and node.func.value.id=='re')
 output.append('pub const FEEDBACK_HEADER_RE: &str = '+json.dumps(pattern(ast.literal_eval(header.args[0])),ensure_ascii=False)+';')
 output.append('pub const UNRESOLVED_EMOJI: &str = '+json.dumps(ast.literal_eval(verdict['_UNRESOLVED_EMOJI_RE'].args[0]),ensure_ascii=False)+';')
 registry=handoff['_MACHINE_TOKEN_STRIP_PATTERNS']
 expected=['vu_done_sentinel','progress_line','verdict']
 if ast.dump(registry.elts[0].elts[1])!=ast.dump(ast.parse('re.compile(re.escape(VU_DONE_SENTINEL))',mode='eval').body):
  raise SystemExit('native sentinel stripping expression changed')
 if [ast.literal_eval(entry.elts[0]) for entry in registry.elts]!=expected:
  raise SystemExit('review native machine-token stripping before changing registry')
 if not (isinstance(registry.elts[1].elts[1],ast.Name) and registry.elts[1].elts[1].id=='_PROGRESS_RE'
    and isinstance(registry.elts[2].elts[1],ast.Name) and registry.elts[2].elts[1].id=='_VERDICT_RE'):
  raise SystemExit('native machine-token pattern references changed')
 strip=next(node for node in ast.parse((ROOT/'lib/agent_verdict/_handoff.py').read_text()).body if isinstance(node,ast.FunctionDef) and node.name=='strip_machine_tokens')
 collapse=next(node for node in ast.walk(strip) if isinstance(node,ast.Call) and isinstance(node.func,ast.Attribute) and node.func.attr=='sub')
 output.append('pub const TOKEN_HUSK_RE: &str = '+json.dumps(ast.literal_eval(collapse.args[0]))+';')
 output.append('pub const TOKEN_HUSK_REPLACEMENT: &str = '+json.dumps(ast.literal_eval(collapse.args[1]))+';')
 output.append('pub const VU_DONE_SENTINEL: &str = '+json.dumps(ast.literal_eval(handoff['VU_DONE_SENTINEL']))+';')
 output.append('pub const WORKER_RATIONALIZATIONS: &[&str] = &['+','.join(json.dumps(value,ensure_ascii=False) for value in ast.literal_eval(verdict['_WORKER_RATIONALIZATIONS']))+'];')
 output.append('pub const WORD_RANGES: &[(u32,u32)] = &['+','.join(f'({a},{b})' for a,b in word)+'];')
 output.append('pub const SPACE_RANGES: &[(u32,u32)] = &['+','.join(f'({a},{b})' for a,b in space)+'];')
 digits=[(code,unicodedata.decimal(chr(code))) for a,b in decimal for code in range(a,b+1)]
 folded=[(code,chr(code).casefold()) for code in range(0x110000) if chr(code).casefold()!=chr(code)]
 output.append('pub const CASEFOLD: &[(u32,&str)] = &['+','.join('('+str(code)+','+json.dumps(value,ensure_ascii=False)+')' for code,value in folded)+'];')
 lower=[(code,chr(code).lower()) for code in range(0x110000) if chr(code).lower()!=chr(code)]
 output.append('pub const LOWERCASE: &[(u32,&str)] = &['+','.join('('+str(code)+','+json.dumps(value,ensure_ascii=False)+')' for code,value in lower)+'];')
 def is_cased(char):return char.islower() or char.isupper() or char.istitle()
 cased=ranges(is_cased)
 # CPython's contextual sigma is the oracle for Case_Ignorable. Cased
 # ignorables must be skipped when scanning backwards; uncased ignorables
 # must be skipped when scanning forwards. No Rust Unicode property is used.
 ignorable=ranges(lambda char: (' '+char+'Σ').lower().endswith('σ') if is_cased(char)
    else ('AΣ'+char+'A').lower()[1]=='σ')
 for name,entries in [('CASED_RANGES',cased),('IGNORABLE_RANGES',ignorable)]:
  output.append('pub const '+name+': &[(u32,u32)] = &['+','.join(f'({a},{b})' for a,b in entries)+'];')
 output.append('pub const DIGITS: &[(u32,u8)] = &['+','.join(f'({code},{value})' for code,value in digits)+'];')
 return '\n'.join(output)+'\n'

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 text=generate()
 outputs={ROOT/'packages/tofu-runtime/src/generated_verdict_policy.rs':text,
    ROOT/'lib/orchestration/native_verdict_contract.py':'"""Generated Unicode identity for the native verifier policy; do not edit."""\nUNICODE_VERSION = '+repr(unicodedata.unidata_version)+'\n'}
 for target,text in outputs.items():
  if args.check:
   if not target.exists() or target.read_text()!=text:raise SystemExit('native verifier generation drift: '+str(target))
  else:target.write_text(text)
if __name__=='__main__':main()
