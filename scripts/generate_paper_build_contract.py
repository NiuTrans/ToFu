"""Generate paper-build types and packaged build/write contracts from their authorities."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/paper_build_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/paper-build.generated.ts'
MCP_OUTPUT = ROOT / 'packages/tofu-overleaf-mcp/tofu_overleaf_mcp/paper_build.generated.json'
WRITE_SOURCE = ROOT / 'contracts/project_file_receipts_v1.schema.json'
WRITE_OUTPUT = MCP_OUTPUT.with_name('file_receipts.generated.json')


from json_schema_types import ts_type


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    text = '// Generated by scripts/generate_paper_build_contract.py; do not edit.\n'
    for name, rule in schema['$defs'].items():
        text += f'export type {name} = {ts_type(rule)};\n\n'
    text += 'export const PAPER_BUILD_LIMITS = ' + json.dumps(schema['x-resource-limits']) + ' as const;\n'
    text += 'export const PAPER_SOURCE_SUFFIXES = ' + json.dumps(schema['x-source-suffixes']) + ' as const;\n'
    outputs = {OUTPUT: text, MCP_OUTPUT: json.dumps(schema, ensure_ascii=False, indent=2) + '\n',
               WRITE_OUTPUT: json.dumps(json.loads(WRITE_SOURCE.read_text()), ensure_ascii=False, indent=2) + '\n'}
    for output, content in outputs.items():
        if args.check:
            if not output.exists() or output.read_text() != content:
                raise SystemExit(f'paper build contract drift: {output.relative_to(ROOT)}')
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(content)


if __name__ == '__main__':
    main()
