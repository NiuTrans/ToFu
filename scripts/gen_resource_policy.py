#!/usr/bin/env python3
"""Generate the stdlib-only bootstrap projection of the resource contract."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]


def generate() -> str:
    document = json.loads((ROOT / 'contracts/resource_policy_v1.json').read_text())
    settings = document['launch_settings']
    defaults = {mode: {name: item['defaults'][mode] for name, item in settings.items()}
                for mode in ('personal', 'distributed')}
    return ('"""Generated by scripts/gen_resource_policy.py; do not edit."""\n\n'
            + 'RESOURCE_FALLBACKS = ' + pprint.pformat(defaults, width=100, sort_dicts=True) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'bootstrap_pkg/resource_policy_generated.py'
    expected = generate()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('resource policy projection is stale; run scripts/gen_resource_policy.py')
    else:
        target.write_text(expected)
