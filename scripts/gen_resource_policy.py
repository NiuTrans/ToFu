#!/usr/bin/env python3
"""Generate the stdlib-only bootstrap projection of the resource contract."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
MODES = ('personal', 'distributed')
CLASSES = ('unlimited', 'fixed', 'retention')


def _validated_settings(document: dict) -> dict:
    settings = document['launch_settings']
    for name, item in settings.items():
        resource_class = item.get('class')
        defaults = item.get('defaults')
        if resource_class not in CLASSES:
            raise SystemExit(f'{name}: class must be one of {", ".join(CLASSES)}')
        if resource_class == 'unlimited':
            if defaults != {mode: 'unlimited' for mode in MODES}:
                raise SystemExit(f'{name}: an unlimited setting defaults to "unlimited" in every mode')
        elif not isinstance(defaults, dict) or set(defaults) != set(MODES) or any(
                type(defaults[mode]) is not int for mode in MODES):
            raise SystemExit(f'{name}: {resource_class} defaults must be integers for {", ".join(MODES)}')
    return settings


def generate(document: dict | None = None) -> str:
    if document is None:
        document = json.loads((ROOT / 'contracts/resource_policy_v1.json').read_text())
    settings = _validated_settings(document)
    classes = {name: item['class'] for name, item in settings.items()}
    defaults = {mode: {name: item['defaults'][mode] for name, item in settings.items()
                       if item['class'] != 'unlimited'}
                for mode in MODES}
    unlimited = sorted(name for name, resource_class in classes.items()
                       if resource_class == 'unlimited')
    return ('"""Generated by scripts/gen_resource_policy.py; do not edit."""\n\n'
            + 'RESOURCE_CLASSES = ' + pprint.pformat(classes, width=100, sort_dicts=True) + '\n\n'
            + 'RESOURCE_FALLBACKS = ' + pprint.pformat(defaults, width=100, sort_dicts=True) + '\n\n'
            + 'UNLIMITED_SETTINGS = frozenset(' + pprint.pformat(unlimited, width=100) + ')\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'bootstrap_pkg/resource_policy_generated.py'
    expected = generate()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('resource policy projection is stale; run scripts/gen_resource_policy.py')
    else:
        target.write_text(expected)
