#!/usr/bin/env python3
"""Translate derived UI locales from the source catalogs through Tofu's LLM API.

Responsibility
    Keep every derived locale declared in ``frontend/src/i18n/languages.json``
    complete and current. Developers author the source locales (``sources``);
    this tool produces every other locale from ALL source versions of each
    string: translate (translator model) -> mechanical validation ->
    independent review (reviewer model) -> adjudication (translator model) ->
    validation -> atomic write. ``translation-sources.json`` records the source
    fingerprint each key was translated from, so edited source copy is
    retranslated instead of silently going stale. ``translation-glossary.json``
    holds the shared terminology; missing glossary translations are produced
    (and reviewed) before any string is translated.

Entry points
    python3 scripts/translate_i18n_locales.py --model M --review-model R
        Translate missing, stale and invalid keys of every derived locale.
    python3 scripts/translate_i18n_locales.py --check
        Offline. Exit 1 while any derived key is missing, stale or invalid.
    --keys a.b,c.d      also retranslate these keys
    --languages ja,ko   restrict the run to some derived locales

    Use the strongest available models from two different model families for
    ``--model`` and ``--review-model``; cross-family review catches errors a
    model tends to repeat.

Dependencies
    The running application's OpenAI-compatible ``/v1/chat/completions``
    (``--api-url``, loopback by default; ``--api-token-env`` names a variable
    holding a bearer token for authenticated deployments). Python stdlib only.
    ``--check`` performs no network access.
"""

