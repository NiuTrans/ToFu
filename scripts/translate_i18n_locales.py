class TranslationToolError(RuntimeError):
    """A precondition or model exchange failed in a way the operator must fix."""


# ── Repository data ──────────────────────────────────────────────────────

@dataclasses.dataclass(frozen=True)
class Language:
    code: str
    tag: str
    name: str
    english_name: str


@dataclasses.dataclass(frozen=True)
class Manifest:
    languages: tuple[Language, ...]
    sources: tuple[str, ...]
    fallback: str

    def language(self, code: str) -> Language:
        return next(language for language in self.languages if language.code == code)

    @property
    def derived(self) -> tuple[Language, ...]:
        return tuple(language for language in self.languages if language.code not in self.sources)


def read_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def write_json_atomic(path: Path, value) -> None:
    text = json.dumps(value, ensure_ascii=False, indent=2) + '\n'
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(text, encoding='utf-8')
    os.replace(temporary, path)


def load_manifest() -> Manifest:
    raw = read_json(MANIFEST_PATH)
    languages = tuple(
        Language(entry['code'], entry['tag'], entry['name'], entry['englishName'])
        for entry in raw['languages']
    )
    codes = [language.code for language in languages]
    sources = tuple(raw['sources'])
    if not sources or not set(sources) <= set(codes) or raw['fallback'] not in sources:
        raise TranslationToolError(f'{MANIFEST_PATH} has invalid sources/fallback')
    for language in languages:
        if language.code not in sources and language.code not in LANGUAGE_POLICIES:
            raise TranslationToolError(
                f'no translation policy for derived language {language.code!r}; '
                'add one to LANGUAGE_POLICIES in this script')
    return Manifest(languages, sources, raw['fallback'])


def load_sources(manifest: Manifest) -> tuple[list[str], dict[str, dict[str, str]]]:
    catalogs = {code: read_json(LOCALE_DIR / f'{code}.json') for code in manifest.sources}
    keys = list(catalogs[manifest.sources[0]])
    for code, catalog in catalogs.items():
        if set(catalog) != set(keys):
            raise TranslationToolError(
                f'source locale {code}.json does not share the key set of '
                f'{manifest.sources[0]}.json; fix the sources first')
    return keys, catalogs


def load_derived(manifest: Manifest) -> dict[str, dict[str, str]]:
    result = {}
    for language in manifest.derived:
        path = LOCALE_DIR / f'{language.code}.json'
        result[language.code] = read_json(path) if path.exists() else {}
    return result


def source_fingerprint(key: str, sources: dict[str, dict[str, str]], manifest: Manifest) -> str:
    payload = '\0'.join(sources[code][key] for code in manifest.sources)
    return hashlib.sha256(payload.encode('utf-8')).hexdigest()[:16]


def load_fingerprints() -> dict[str, str]:
    if not FINGERPRINTS_PATH.exists():
        return {}
    return dict(read_json(FINGERPRINTS_PATH).get('fingerprints') or {})


def load_glossary() -> dict:
    return read_json(GLOSSARY_PATH)


def namespace_of(key: str) -> str:
    return key.split('.', 1)[0]


# ── Mechanical validation ────────────────────────────────────────────────

def placeholder_names(text: str) -> set[str]:
    return set(PLACEHOLDER_RE.findall(text))


def _edges(text: str) -> tuple[str, str]:
    return LEADING_WS_RE.match(text).group(0), TRAILING_WS_RE.search(text).group(0)


def validate_translation(
    language: str, text: object, source_values: dict[str, str], fallback: str,
) -> tuple[list[str], list[str]]:
    """Return ``(errors, warnings)``; any error makes the translation unusable."""
    if not isinstance(text, str):
        return ['translation is not a string'], []
    policy = LANGUAGE_POLICIES[language]
    values = list(source_values.values())
    reference = source_values[fallback]
    errors: list[str] = []
    warnings: list[str] = []

    if not text.strip():
        # An empty source (e.g. a prefix English does not need) may stay empty.
        return ([], []) if text in values else (['empty translation'], [])
    if all(not value.strip() for value in values):
        errors.append('sources are empty, so the translation must be empty')

    names = placeholder_names(text)
    counts = collections.Counter(PLACEHOLDER_RE.findall(text))
    most = collections.Counter()
    for value in values:
        most |= collections.Counter(PLACEHOLDER_RE.findall(value))
    repeated = sorted(name for name, count in counts.items() if count > most.get(name, 0) > 0)
    if repeated:
        # Some call sites substitute only the first occurrence of a placeholder.
        errors.append(f'placeholders used more often than in the source: {repeated}')
    allowed = set().union(*(placeholder_names(value) for value in values))
    required = set.intersection(*(placeholder_names(value) for value in values))
    if not policy.plural_suffix_allowed:
        allowed.discard(ENGLISH_PLURAL_SUFFIX)
    required.discard(ENGLISH_PLURAL_SUFFIX)
    if names - allowed:
        errors.append(f'unknown or forbidden placeholders {sorted(names - allowed)}; '
                      f'allowed {sorted(allowed)}')
    if required - names:
        errors.append(f'missing placeholders {sorted(required - names)}')

    tags = collections.Counter(TAG_RE.findall(text))
    if tags not in [collections.Counter(TAG_RE.findall(value)) for value in values]:
        errors.append('HTML tags differ from the source (keep every tag and attribute exactly)')

    source_urls = [set(URL_RE.findall(value)) for value in values]
    missing_urls = set.intersection(*source_urls) - set(URL_RE.findall(text))
    if missing_urls:
        errors.append(f'URLs changed or missing: {sorted(missing_urls)}')

    if text.count('\n') not in {value.count('\n') for value in values}:
        errors.append('line-break count differs from the source')

    leading, trailing = _edges(text)
    if leading not in {_edges(value)[0] for value in values}:
        errors.append('leading whitespace differs from the source')
    if trailing not in {_edges(value)[1] for value in values}:
        errors.append('trailing whitespace differs from the source')

    if not policy.han_allowed and HAN_RE.search(text) and not HAN_RE.search(reference):
        errors.append('contains Chinese characters')

    sources_agree = len(set(values)) == 1
    # Acronyms (API, URL, PDF) legitimately stay in Latin script everywhere.
    word_count = sum(
        1 for word in LATIN_WORD_RE.findall(PLACEHOLDER_RE.sub(' ', TAG_RE.sub(' ', reference)))
        if not word.isupper())
    if not sources_agree:
        if policy.native_script and word_count >= 2 and not any(
                pattern.search(text) for pattern in policy.native_script):
            errors.append(f'no {language} script in the translation (left untranslated?)')
        elif not policy.native_script and word_count >= 3 and text == reference:
            errors.append('identical to the English source (left untranslated?)')

    for span in CODE_SPAN_RE.findall(reference):
        if span not in text:
            warnings.append(f'code span {span} not kept verbatim')
    longest = max(len(value) for value in values)
    if len(text) > 3 * longest + 20:
        warnings.append('much longer than the source')
    return errors, warnings


# ── Usage context ────────────────────────────────────────────────────────

_QUOTED_TOKEN_RE = re.compile(r'["\'`]([A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)*\.?)["\'`$]')
_USAGE_ROOTS = ('frontend/src', 'static/settings_panels', 'index.html', 'static/admin.html')


def _usage_files() -> list[Path]:
    try:
        listed = subprocess.run(
            ['git', 'ls-files', *_USAGE_ROOTS], cwd=ROOT, capture_output=True,
            text=True, check=True,
        ).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        listed = [str(path.relative_to(ROOT)) for root in _USAGE_ROOTS
                  for path in (ROOT / root).rglob('*') if path.is_file()]
    return [
        ROOT / name for name in listed
        if name.endswith(('.ts', '.js', '.html'))
        and '.generated.' not in name and not name.endswith('app-runtime.js')
        and '.test.' not in name and '/testing/' not in name
    ]


def build_usage_index(keys: list[str]) -> dict[str, str]:
    """Map keys to one source line that renders them (literal or key family)."""
    wanted = set(keys)
    literal: dict[str, str] = {}
    prefixes: dict[str, str] = {}
    for path in _usage_files():
        try:
            lines = path.read_text(encoding='utf-8').splitlines()
        except (OSError, UnicodeDecodeError):
            continue
        relative = path.relative_to(ROOT).as_posix()
        for line in lines:
            for match in _QUOTED_TOKEN_RE.finditer(line):
                token = match.group(1)
                snippet = f'{relative}: {line.strip()[:220]}'
                if token in wanted:
                    literal.setdefault(token, snippet)
                elif token.endswith('.'):
                    prefixes.setdefault(token, snippet)
    index = dict(literal)
    for key in keys:
        if key in index:
            continue
        parts = key.split('.')
        for size in range(len(parts) - 1, 0, -1):
            prefix = '.'.join(parts[:size]) + '.'
            if prefix in prefixes:
                index[key] = prefixes[prefix] + '  (key family)'
                break
    return index


# ── Model client ─────────────────────────────────────────────────────────

class ChatClient:
    """OpenAI-compatible chat client with a content-addressed response cache."""

    def __init__(self, api_url: str, token: str | None, cache_dir: Path, log=None) -> None:
        self.endpoint = api_url.rstrip('/') + '/v1/chat/completions'
        self.token = token
        self.cache_dir = cache_dir
        self.log = log or (lambda message: None)
        cache_dir.mkdir(parents=True, exist_ok=True)

    def complete_json(self, model: str, system: str, user: str) -> dict:
        """Return the reply as a JSON object; only parseable replies are cached."""
        payload = {
            'model': model,
            'messages': [{'role': 'system', 'content': system},
                         {'role': 'user', 'content': user}],
            'max_tokens': MAX_OUTPUT_TOKENS,
            'temperature': 0,
        }
        body = json.dumps(payload, ensure_ascii=False, sort_keys=True).encode('utf-8')
        cache_path = self.cache_dir / (hashlib.sha256(body).hexdigest() + '.txt')
        if cache_path.exists():
            return parse_json_object(cache_path.read_text(encoding='utf-8'))
        headers = {'Content-Type': 'application/json'}
        if self.token:
            headers['Authorization'] = f'Bearer {self.token}'
        last_error = ''
        for attempt in range(REQUEST_ATTEMPTS):
            if attempt:
                self.log(f'{model}: retry {attempt}/{REQUEST_ATTEMPTS - 1} after {last_error[:160]}')
                time.sleep(min(120, 5 * 2 ** (attempt - 1)))
            request = urllib.request.Request(self.endpoint, data=body, headers=headers, method='POST')
            try:
                with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT_S) as response:
                    data = json.loads(response.read().decode('utf-8'))
            except urllib.error.HTTPError as error:
                detail = error.read().decode('utf-8', 'replace')[:300]
                last_error = f'HTTP {error.code}: {detail}'
                if error.code in (408, 409, 425, 429) or error.code >= 500:
                    continue
                raise TranslationToolError(f'{model}: {last_error}') from error
            except (urllib.error.URLError, TimeoutError, OSError, ValueError) as error:
                last_error = f'{type(error).__name__}: {error}'
                continue
            content = _message_text(data)
            try:
                value = parse_json_object(content)
            except TranslationToolError:
                last_error = f'reply is not a JSON object: {content[:300]!r}'
                continue
            cache_path.write_text(content, encoding='utf-8')
            return value
        raise TranslationToolError(f'{model}: request failed after {REQUEST_ATTEMPTS} attempts: {last_error}')


def _message_text(data: dict) -> str:
    try:
        content = data['choices'][0]['message']['content']
    except (KeyError, IndexError, TypeError):
        return ''
    if isinstance(content, list):
        return ''.join(part.get('text', '') for part in content if isinstance(part, dict))
    return content if isinstance(content, str) else ''


def parse_json_object(text: str) -> dict:
    """Return the first complete JSON object in a reply, ignoring surrounding prose.

    Prose after the object may contain braces of its own (placeholders such as
    {n}), so the object is decoded from its opening brace, never sliced to the
    last closing brace.
    """
    fence = re.search(r'```(?:json)?\s*(.*?)```', text, re.S)
    decoder = json.JSONDecoder()
    for candidate in ([fence.group(1)] if fence else []) + [text]:
        start = candidate.find('{')
        while start != -1:
            try:
                value, _end = decoder.raw_decode(candidate, start)
            except ValueError:
                start = candidate.find('{', start + 1)
                continue
            if isinstance(value, dict):
                return value
            start = candidate.find('{', start + 1)
    raise TranslationToolError('model reply is not a JSON object')


