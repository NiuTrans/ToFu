"""Generate independently packaged worker code from its single stdlib owner.

Source: tofu_workers/executor.py. Outputs are private package modules; runtime
imports never reach outside an installed package. --check is read-only.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tofu_workers/executor.py'
OUTPUTS = (
    ROOT / 'packages/tofu-search/tofu_search/_worker_executor.py',
    ROOT / 'plugins/tofu-trading/tofu_trading/_worker_executor.py',
)


def generated_bytes():
    source = SOURCE.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    header = ('# Generated by scripts/gen_packaged_demand_workers.py; do not edit.\n'
              '# Authority: tofu_workers/executor.py (MIT).\n'
              '# Copyright (c) 2026 Tofu contributors.\n'
              f'# Source SHA256: {digest}\n')
    return header.encode() + source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated_bytes()
    stale = []
    for output in OUTPUTS:
        if args.check:
            if not output.is_file() or output.read_bytes() != expected:
                stale.append(str(output.relative_to(ROOT)))
        else:
            output.write_bytes(expected)
    if stale:
        raise SystemExit('Regenerate packaged demand workers: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
