"""Generate channel DTOs from the canonical schema; --check detects drift."""
import argparse
import json
from pathlib import Path

from json_schema_types import ts_type

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/channels_v1.schema.json'
OUTPUT = ROOT / 'frontend/src/api/channels.generated.ts'


def render() -> str:
    schema = json.loads(SOURCE.read_text(encoding='utf-8'))
    content = '// Generated by scripts/gen_channels_contract.py; do not edit.\n'
    content += f'export const CHANNEL_DISCLOSURE_LABEL = {json.dumps(schema["x-disclosureLabel"], ensure_ascii=False)};\n'
    content += 'export const CHANNEL_DEFAULT_MODE_BY_KIND = ' + json.dumps(
        schema['x-defaults']['modeByKind']) + ' as const;\n'
    content += f'export const CHANNEL_DEFAULT_REPLY_POLICY = {json.dumps(schema["x-defaults"]["replyPolicy"])};\n\n'
    for name, rule in schema['$defs'].items():
        content += f'export type {name} = {ts_type(rule)};\n\n'
    return content


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Channels contract drift: run npm run generate:channels')
    else:
        OUTPUT.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
